  function build(ch, front) {
    var list = IMAGERY[ch];
    if (!list) return '';
    var out = [];
    for (var i = 0; i < list.length; i++) {
      var it = list[i];
      if (!!it.front !== !!front) continue;
      var pts = it.p.map(function (q) { return { x: q[0], y: q[1] }; });
      out.push(root.InkBrush.strokeEl(pts, {
        w: it.w, profile: it.prof, tone: it.tone,
        asym: it.asym == null ? 0 : it.asym,
        fade: it.fade || 'none',
        opacity: it.opacity == null ? 1 : it.opacity,
        seg: it.seg || 18
      }));
    }
    return out.join('');
  }

