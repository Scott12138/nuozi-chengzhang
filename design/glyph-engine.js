/* ============================================================================
 * 挪字成章 · 「字物合一」字形引擎
 * ----------------------------------------------------------------------------
 * 设计原则（三条，缺一条就退化成普通美术字）：
 *   ① 先立楷体骨架 —— 每个字的笔画位置 = 标准楷体的位置，这是「可辨认」的底线
 *   ② 笔画上生长物象 —— 不额外贴一个插图，而是让笔画本身变成物（木=树干+枝+根）
 *   ③ 物象不许破坏骨架 —— 加叶子、加火星、加流苏都必须落在笔画外侧，不遮挡结构
 *
 * 用法：
 *   brush([[50,10],[50,90]], 5, 9)   -> 一条带收锋的笔迹 path d
 *   glyphSVG('木', {ink:'var(--mo-2)'}) -> 完整 <svg> 字符串
 *
 * 为什么用「折线 + 自动生成笔迹」而不是手画 path：
 *   119 个字形要风格统一。手画 path 每个字的笔锋都不一样，越画越散。
 *   折线好写好调，笔锋由引擎统一算，改一处参数全局生效。
 * ========================================================================== */

/* ---------------------------------------------------------------- 笔迹生成 */
/**
 * 把折线变成「中间粗、两端收锋」的填充笔迹。
 * @param {Array<[number,number]>} pts 折线顶点
 * @param {number} w0 起笔宽度  @param {number} w1 收笔宽度
 * @param {object} [opt] head/tail 收锋区段占比；capS/capE 收锋强度(0~1)
 */
function brush(pts, w0, w1, opt) {
  opt = opt || {};
  const n = pts.length;
  if (n < 2) return '';

  // 弧长参数化 —— 收锋要按「走了多远」算，不能按顶点序号算
  const L = [0];
  let tot = 0;
  for (let i = 1; i < n; i++) {
    tot += Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]);
    L.push(tot);
  }
  if (tot < 1e-6) return '';

  const head = opt.head === undefined ? 0.16 : opt.head;
  const tail = opt.tail === undefined ? 0.26 : opt.tail;
  const capS = opt.capS === undefined ? 0.50 : opt.capS;
  const capE = opt.capE === undefined ? 0.72 : opt.capE;

  const Ls = [], Rs = [];
  for (let i = 0; i < n; i++) {
    const t = L[i] / tot;
    let f = 1;
    if (t < head)            f = (1 - capS) + capS * (t / head);
    else if (t > 1 - tail)   f = (1 - capE) + capE * ((1 - t) / tail);
    const w = (w0 + (w1 - w0) * t) * f;

    const p0 = pts[Math.max(0, i - 1)], p1 = pts[Math.min(n - 1, i + 1)];
    let dx = p1[0] - p0[0], dy = p1[1] - p0[1];
    const d = Math.hypot(dx, dy) || 1;
    dx /= d; dy /= d;
    Ls.push([pts[i][0] - dy * w / 2, pts[i][1] + dx * w / 2]);
    Rs.push([pts[i][0] + dy * w / 2, pts[i][1] - dx * w / 2]);
  }

  const r = v => Math.round(v * 100) / 100;
  const P = p => r(p[0]) + ' ' + r(p[1]);

  let d = 'M' + P(Ls[0]);
  for (let i = 1; i < n; i++) d += 'L' + P(Ls[i]);

  // 收笔的圆头：用一条二次曲线绕过笔尖（比 arc 命令可靠，不会有 sweep 方向歧义）
  let ex = pts[n - 1][0] - pts[n - 2][0], ey = pts[n - 1][1] - pts[n - 2][1];
  let en = Math.hypot(ex, ey) || 1;
  d += 'Q' + P([pts[n - 1][0] + ex / en * w1 * 0.55, pts[n - 1][1] + ey / en * w1 * 0.55]) + ' ' + P(Rs[n - 1]);

  for (let i = n - 2; i >= 0; i--) d += 'L' + P(Rs[i]);

  // 起笔的圆头
  let sx = pts[0][0] - pts[1][0], sy = pts[0][1] - pts[1][1];
  let sn = Math.hypot(sx, sy) || 1;
  d += 'Q' + P([pts[0][0] + sx / sn * w0 * 0.55, pts[0][1] + sy / sn * w0 * 0.55]) + ' ' + P(Ls[0]);

  return d + 'Z';
}

