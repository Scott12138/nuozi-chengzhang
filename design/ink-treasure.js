  /**
   * 把一串绝对坐标路径整体平移。
   * 写这里是为了让"暗面 = 同一批图形偏移一下"这件事读起来是**一个意图**，
   * 而不是 20 条手算坐标（那种写法迟早有一条抄错，而且不报错）。
   *
   * ⚠️ **不能简单地把数字两两配对去加偏移** —— 路径里除了坐标还有别的数字：
   *   `A 27 27 0 1 0 347 360` 里，`27 27` 是半径、`0 1 0` 是旋转与大弧/扫向标志，
   *   只有最后两个才是坐标。两两配对去加，会把弧的 flags 一起平移，
   *   结果是算珠被画成歪的、或者干脆不显示——**静默坏**。
   *   所以这里按**命令**逐段处理：M/L 每 2 个数一对、C 每 6 个、A 每 7 个且只动最后两个。
   */
  function shiftPath(d, dx, dy) {
    if (/[mlcazsqtvh]/.test(d)) {
      throw new Error('shiftPath 只接受绝对坐标路径：' + d.slice(0, 40));
    }
    var one = function (n) { return String(Math.round(n * 10) / 10); };
    var re = /([A-Za-z])([^A-Za-z]*)/g, m, out = [];
    while ((m = re.exec(d)) !== null) {
      var cmd = m[1];
      if (cmd === 'Z') { out.push('Z'); continue; }
      var nums = (m[2].match(/-?\d*\.?\d+/g) || []).map(Number);
      var step = cmd === 'C' ? 6 : cmd === 'A' ? 7 : 2;
      if (!nums.length || nums.length % step !== 0) {
        throw new Error('shiftPath 无法解析：' + cmd + ' 参数 ' + nums.length + ' 个');
      }
      var seg = [];
      for (var i = 0; i < nums.length; i += step) {
        if (cmd === 'A') {
          /* rx ry rot large sweep x y —— 只有最后两个是坐标 */
          seg.push(nums.slice(i, i + 5).map(one).join(' ') + ' '
            + one(nums[i + 5] + dx) + ' ' + one(nums[i + 6] + dy));
        } else {
          var p = [];
          for (var j = 0; j < step; j += 2) {
            p.push(one(nums[i + j] + dx) + ' ' + one(nums[i + j + 1] + dy));
          }
          seg.push(p.join(' '));
        }
      }
      out.push(cmd + ' ' + seg.join(' '));
    }
    return out.join(' ');
  }

