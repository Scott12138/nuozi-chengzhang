/**
 * ============================================================
 *  LevelSeeds.ts · 每关 4 颗「开局已验证有解」的固定种子（生成物，勿手改）
 * ============================================================
 *  生成器：`node tools/gen-level-seeds.js`
 *
 *  【它解决什么】
 *  用户拍过「每一关做完设计后固定下来，开局要确定有解」。但发牌是随机的，
 *  实测（36 关 × 8 盘）**只有 84% 的随机开局有解** —— 20 关会发到死局盘面。
 *  现在改成：每关固定这 4 颗种子，开局从里面随机挑一颗。
 *  这 4 颗**每一颗都经求解器判定为有解**（判据口径 bonus=none，见
 *  tools/solve-exact.js 文件头），而且是**离线**判定的 ⇒ 手机端零额外开销。
 *
 *  【LEVEL_BOARD_FP 是干什么的】
 *  种子表有没有跟上"当前的发牌实现"，不能靠人记。这里存下每颗种子当时
 *  的发牌指纹（`Board.fingerprint()`），`tools/core-selftest.js` 每次自检
 *  重算一遍比对：**对不上 ⇒ 发牌路径动过了 ⇒「这四局有解」已过期 ⇒
 *  重跑 `node tools/gen-level-seeds.js`**。
 *  ⚠️ 自检只能查"路径没变"，查不出"路径变了但指纹恰好一样"（32 位，约 3e-6）；
 *     真正的有解性复核是 `node tools/gen-level-seeds.js --verify`，发布前跑一次。
 *
 *  ⚠️ 关卡数据（LevelData.ts）一改，就**必须**重跑生成器：
 *     `lv.words / pairs / tr / ch` 任一变化都会让这 4 局的盘面变样。
 * ============================================================
 */

