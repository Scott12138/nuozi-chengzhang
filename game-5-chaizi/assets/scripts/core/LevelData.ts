/** 关号 → 关卡定义（越界返回 undefined，调用方自己兜） */
export function levelByN(n: number): LevelDef | undefined {
    return LEVELS.find((l) => l.n === n);
}

/** 章节 → 该章的关卡数组 */
export function levelsOfChapter(ch: number): LevelDef[] {
    return LEVELS.filter((l) => l.ch === ch);
}

/** 该关当前是否可玩（贴图/机制是否已备齐）。2026-10-03 起恒为 true。 */
export function isPlayable(lv: LevelDef): boolean {
    return lv.n <= PLAYABLE_MAX;
}

