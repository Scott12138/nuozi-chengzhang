// ------------------------------------------------------------
//  极简 CDP 客户端
// ------------------------------------------------------------
class CDP {
    /**
     * 单条 CDP 命令的默认超时（ms）。
     * ⚠️ 别设小。它的作用只是"别永久挂死"，不是"催我快点"——
     *   crash 过的两个值都在这台机器上误报过：
     *     · 20s  → 首次加载时 Cocos 的 cocos-js 还在编译，渲染进程不响应；
     *     · 60s  → 系统负载高时（实测 load average ≈ 9，无头 Chrome 走
     *              swiftshader **软件渲染**，主线程被 WebGL 绘制占满）
     *              也会超。
     *   120s 是"正常情况永远够、真挂死也能报出来"的折中。
     */
    static CMD_TIMEOUT_MS = 120000;
    /** 截图命令的超时（ms）—— 整屏 PNG + base64 回传本来就慢 */
    static SHOT_TIMEOUT_MS = 120000;

    constructor(ws) {
        this.ws = ws;
        this.seq = 0;
        this.pending = new Map();
        this.consoleLines = [];
        // 【为什么每条都立刻落盘，而不是最后统一 writeFileSync】
        // 页面控制台是这条命令行链路下**唯一的可观测性来源**（游戏自己打的
        // 「牌局 / 消除 牌型=…」全在里面）。而一次完整的冒烟要跑两三分钟，
        // 一旦中途被外部打断（实测遇到过一次：进程被 SIGKILL，正是卡在
        // 「吃」的连拍中间），只靠收尾那次写文件就会**把最关键的那几行丢掉**，
        // 而恰好丢的就是"这一步消了什么牌型、走了哪套动效"。
        // 改成随到随写，任何时刻中断都能拿到截止那一刻的完整日志。
        this.consolePath = `${OUT_DIR}/console.log`;
        writeFileSync(this.consolePath, '');
        // 录屏帧流（见 startScreencast）。null = 没在录。
        this.screencast = null;
        ws.addEventListener('message', (ev) => {
            const msg = JSON.parse(ev.data);
            if (msg.id && this.pending.has(msg.id)) {
                const { resolve, reject, timer } = this.pending.get(msg.id);
                this.pending.delete(msg.id);
                if (timer) clearTimeout(timer);          // 别让超时定时器在应答后才开火
                msg.error ? reject(new Error(JSON.stringify(msg.error))) : resolve(msg.result);
                return;
            }
            // ★ 录屏帧：必须**逐帧回执**（screencastFrameAck）。
            //   不回执 Chrome 就认为前端消费不过来，直接停推流 ——
            //   表现是"录了 3 秒只拿到 1 帧"，而且不会有任何报错。
            if (msg.method === 'Page.screencastFrame') {
                const p = msg.params;
                if (this.screencast) {
                    this.screencast.frames.push({ ts: Date.now() - this.screencast.t0, data: p.data });
                }
                this.send('Page.screencastFrameAck', { sessionId: p.sessionId }).catch(() => { });
                return;
            }
            // 收集页面控制台输出（这是命令行构建下拿不到的最关键信息）
            if (msg.method === 'Runtime.consoleAPICalled') {
                const text = (msg.params.args || [])
                    .map((a) => a.value ?? a.description ?? a.type)
                    .join(' ');
                this.push(`[${msg.params.type}] ${text}`);
            }
            if (msg.method === 'Log.entryAdded') {
                this.push(`[log:${msg.params.entry.level}] ${msg.params.entry.text}`);
            }
            if (msg.method === 'Runtime.exceptionThrown') {
                const d = msg.params.exceptionDetails;
                const desc = d.exception?.description || d.text;
                this.push(`[exception] ${desc}`);
            }
        });
    }

    push(line) {
        this.consoleLines.push(line);
        try {
            appendFileSync(this.consolePath, line + '\n');
        } catch { /* 落盘失败不影响测试本身 */ }
    }

    send(method, params = {}, timeoutMs = CDP.CMD_TIMEOUT_MS) {
        const id = ++this.seq;
        return new Promise((resolve, reject) => {
            // ★ 每条命令都必须有超时。
            //   踩过的坑：CDP 的应答一旦丢失（WebSocket 半死、渲染进程忙到不响应、
            //   Chrome 被外部杀掉），Promise 永远不 settle —— 表现是脚本**静默卡死**，
            //   最后只留一句 `Warning: Detected unsettled top-level await`，
            //   完全看不出卡在哪一步、为什么卡。加了超时就能指名道姓地报出来。
            const timer = setTimeout(() => {
                if (!this.pending.has(id)) return;
                this.pending.delete(id);
                reject(new Error(`CDP ${method} 超过 ${timeoutMs}ms 没有应答（连接半死或页面无响应）`));
            }, timeoutMs);
            this.pending.set(id, { resolve, reject, timer });
            try {
                this.ws.send(JSON.stringify({ id, method, params }));
            } catch (e) {
                clearTimeout(timer);
                this.pending.delete(id);
                reject(new Error(`CDP ${method} 发送失败：${e && e.message}`));
            }
        });
    }

    /** 在页面里求值，返回 JSON 解析后的结果 */
    async evaluate(expression) {
        const r = await this.send('Runtime.evaluate', {
            expression, returnByValue: true, awaitPromise: false,
        });
        if (r.exceptionDetails) {
            // ⚠️ 只报 `exceptionDetails.text` 是不够的 —— 页面里抛出的 JS 异常，
            //    text 往往就是一个 "Uncaught"，真正有用的堆栈/消息在 exception.description 里。
            //    （2026-10-02 踩到：探针一直只报 "Uncaught"，完全看不出是
            //     `cc.Graphics is not a constructor` 还是别的。）
            const d = r.exceptionDetails;
            throw new Error(d.exception?.description || d.text || '未知异常');
        }
        return r.result.value;
    }

    async shot(name) {
        // 截图单独放宽超时：整屏 PNG（600×1260）+ base64 回传本来就慢，
        // 用命令的默认超时会在真机上偶发误报。
        const { data } = await this.send('Page.captureScreenshot', { format: 'png' },
            CDP.SHOT_TIMEOUT_MS);
        const p = `${OUT_DIR}/${name}.png`;
        writeFileSync(p, Buffer.from(data, 'base64'));
        return p;
    }

    /**
     * **只抓一块区域**的截图（CDP `clip`）。动效连拍必须用它。
     *
     * 【为什么非它不可 —— 2026-10-02 实测】
     * 整屏 600×1260 = 756k 像素，`Page.captureScreenshot` 从发出请求到真正成像
     * 要 **120~190ms**（实测：请求 +0ms 的那张，帧落在 +0~125ms）。
     * 而合并撞击的挤压窗口只有 **70ms** ——
     * 用整屏抓，时间分辨率比事件本身还粗，等于闭着眼睛拍。
     *
     * 裁到"拖拽那一带"（约 600×160 = 96k 像素，缩到 1/8）之后，
     * 单张延迟降到几十毫秒量级，才谈得上"抓中间帧"。
     *
     * @param clip {x,y,width,height,scale} —— 屏幕 CSS 像素，左上角为原点
     */
    async shotClip(name, clip) {
        const { data } = await this.send('Page.captureScreenshot', {
            format: 'png',
            clip: {
                x: Math.max(0, Math.round(clip.x)),
                y: Math.max(0, Math.round(clip.y)),
                width: Math.round(clip.width),
                height: Math.round(clip.height),
                scale: clip.scale ?? 1,
            },
        }, CDP.SHOT_TIMEOUT_MS);
        const p = `${OUT_DIR}/${name}.png`;
        writeFileSync(p, Buffer.from(data, 'base64'));
        return p;
    }

    /** 在指定屏幕坐标模拟一次"移动 → 按下 → 抬起"（Cocos 靠这套事件驱动按钮） */
    async clickAt(x, y) {
        const base = { x, y, button: 'left', clickCount: 1 };
        await this.send('Input.dispatchMouseEvent', { type: 'mouseMoved', ...base, button: 'none' });
        await sleep(60);
        await this.send('Input.dispatchMouseEvent', { type: 'mousePressed', ...base });
        await sleep(90);
        await this.send('Input.dispatchMouseEvent', { type: 'mouseReleased', ...base });
    }

    /**
     * 真·拖拽：移动 → 按下 → **多段插值移动** → 抬起。
     *
     * 【为什么必须分段，不能"按下 → 直接跳到终点 → 抬起"】
     * Cocos 的拖动靠 TOUCH_MOVE 累积位移来判定方向和轴锁定（横滑还是竖滑，
     * 见 GamePage.onMove 的 axis 逻辑）。只派一次终点移动，位移向量虽然对，
     * 但引擎内部的 move 事件序列只有一跳；更关键的是**中间会跳过错失吸附、
     * 预判高亮等依赖"过程"的逻辑**，而玩家真实拖动一定是有过程的。
     * 分段插值让测试路径与真人路径一致。
     *
     * 【为什么要带 motion/buttons】
     * mouseMoved 若不带 buttons=1，浏览器会认为"没有按键按下"，
     * 拖拽语义就退化成单纯移动指针 —— 页面收不到"带按下的移动"。
     *
     * 【hooks：动效取证用的两个截帧点（2026-10-02 加）】
     *   midShot: { atT, name } —— 拖到插值进度 atT（0~1）时**松手前**截一张。
     *     ★ 口径 2026-10-03 换过，别照抄旧版：现在是**整格吸附**，所以这一帧的
     *       正确判读是"牌**正好落在某一格的格心**、角度为 0、且仍在棋盘内"。
     *       旧版口径是"牌必须停在**手指所在的位置**（而不是被吸附到格中心）"，
     *       那条与"跟手自由滑 + 越界橡皮筋"的旧实现自洽，但**旧实现是错的**
     *       （用户真机试玩三条原话，见文件头「手感三处怎么取证」的 ②）。
     *     ⚠️ 想拿硬判据就别看图，用 `dragcell:` —— 它逐格断言
     *        `[Diag] DRAG` 的 节点===期望 / 角度===0 / 格在棋盘内。
     *   burst: [{off, name}] —— 松手后按 off 毫秒偏移连拍。
     *     撞击动效只有 ~70ms 的挤压窗 + ~230ms 的飞行，靠普通"点完等 1.6s 再截"
     *     永远只能拍到已经结束的画面，必须按偏移连拍。
     *   ⚠️ 指针停在 move 中途截图时，鼠标仍处于按下状态 —— 截完继续走完剩余插值。
     */
    async dragAt(x1, y1, x2, y2, steps = 10, hooks = {}) {
        const { midShot = null, burst = null } = hooks;
        const pt = (x, y, extra = {}) => ({
            x: Math.round(x), y: Math.round(y), button: 'left', clickCount: 1, ...extra,
        });
        await this.send('Input.dispatchMouseEvent', { ...pt(x1, y1), type: 'mouseMoved', button: 'none' });
        await sleep(50);
        await this.send('Input.dispatchMouseEvent', { ...pt(x1, y1), type: 'mousePressed', buttons: 1 });
        await sleep(50);
        const midAt = midShot ? Math.max(1, Math.round(steps * (midShot.atT ?? 0.5))) : -1;
        for (let i = 1; i <= steps; i++) {
            const t = i / steps;
            await this.send('Input.dispatchMouseEvent', {
                ...pt(x1 + (x2 - x1) * t, y1 + (y2 - y1) * t),
                type: 'mouseMoved',
                buttons: 1,
            });
            await sleep(18);
            if (i === midAt) await this.take(midShot.name, midShot.clip);
        }
        await sleep(50);
        await this.send('Input.dispatchMouseEvent', { ...pt(x2, y2), type: 'mouseReleased' });
        if (burst && burst.length) {
            // ★ 补偿必须按**真实耗时**算，不能累加"请求值"。
            //   若写成 `sleep(off - 上一个请求值)`，误差会一路累积 —— 第 5 张起就完全对不上号。
            //   这里每张开拍前先问"现在离释放过了多少"，只补差值。
            //
            // ⚠️ 仍然要说清楚：`before` 只是"发出抓取请求"的时刻，真正的帧落在
            //   `[before, after]` 这个区间里（CDP 处理 + 合成 + 编码都要时间）。
            //   想抓只有 70ms 宽的挤压窗口，这个区间的宽度就是精度上限 ——
            //   所以**必须用 shotClip 裁小区域**把 after-before 压到几十毫秒，
            //   并让偏移留重叠（下面默认是 40ms 的梳齿），别指望一张就中。
            const t0 = Date.now();
            for (const b of burst) {
                const wait = b.off - (Date.now() - t0);
                if (wait > 0) await sleep(wait);
                const before = Date.now() - t0;
                const p = await this.take(b.name, b.clip);
                const after = Date.now() - t0;
                console.log(`      连拍 ${p.split('/').pop()}：`
                    + `请求 +${b.off}ms，实际帧落在 +${before}~${after}ms`);
            }
        }
        await sleep(60);
    }

    /** 有 clip 就裁区域抓（快，用于连拍），否则整屏抓（慢，用于留档） */
    async take(name, clip) {
        return clip ? this.shotClip(name, clip) : this.shot(name);
    }

    // ------------------------------------------------------------
    //  ★ 录屏：动效取证的"正确工具"（2026-10-02 加）
    // ------------------------------------------------------------
    /**
     * 【为什么单张截图这条路走不通】
     * 合并撞击的挤压只有 **70ms**，而 `Page.captureScreenshot` 即使裁到一小块，
     * 从发请求到真正成像也要 **50~60ms**（整屏更是 120~190ms，实测）。
     * 也就是说"单拍"的时间分辨率比事件本身还粗 —— 能不能拍到全看运气，
     * 而且拍到了也无法证明它落在窗口内的哪一刻。
     * 本轮第一次尝试用 40/90/160/260 四张偏移，结果**四张全 miss**
     * （前两张在落位阶段、后两张已经开始飞走）。
     *
     * 【screencast 好在哪】
     * `Page.startScreencast` 是**推送式**：Chrome 每合成一帧就把 JPEG 推过来，
     * 每帧自带到达时间。于是拿到的是"一段时间轴上的帧序列 + 时间戳"，
     * 而不是"若干张各自有几十毫秒不确定度的孤立照片"。
     *
     * 【参数取舍】
     *   · format 用 **jpeg**：PNG 编码一帧 600×1260 就要几十毫秒，会把帧率压到个位数；
     *     jpeg quality 85 快得多，动效取证看的是形变不是像素精度。
     *   · maxWidth/maxHeight 限制在视口尺寸，不要放大（放大只增加编码时间）。
     *   · everyNthFrame = 1（每帧都要）。
     * ⚠️ 录制本身有开销（每帧一次 JPEG 编码 + 一次 WS 回执），会轻微拖慢渲染。
     *    所以"帧率"只能当**下限**看 —— 真实设备上的动效只会更顺，
     *    不会因为录制才变卡。
     */
    async startScreencast(opts = {}) {
        this.screencast = { frames: [], t0: Date.now() };
        await this.send('Page.startScreencast', {
            format: opts.format ?? 'jpeg',
            quality: opts.quality ?? 85,
            maxWidth: opts.maxWidth ?? 600,
            maxHeight: opts.maxHeight ?? 1260,
            everyNthFrame: opts.everyNthFrame ?? 1,
        });
    }

    /**
     * 停止录制并把帧落盘。
     * @returns {{count:number, span:number, fps:number}}
     */
    async stopScreencast(name) {
        const sc = this.screencast;
        this.screencast = null;
        try { await this.send('Page.stopScreencast'); } catch { /* 没在录也无所谓 */ }
        if (!sc || !sc.frames.length) return { count: 0, span: 0, fps: 0 };
        const lines = [];
        sc.frames.forEach((f, k) => {
            const fn = `${name}-${String(k).padStart(3, '0')}.jpg`;
            writeFileSync(`${OUT_DIR}/${fn}`, Buffer.from(f.data, 'base64'));
            lines.push(`${fn}\t+${f.ts}ms`);
        });
        const span = sc.frames[sc.frames.length - 1].ts;
        writeFileSync(`${OUT_DIR}/${name}-frames.txt`, lines.join('\n') + '\n');
        return {
            count: sc.frames.length,
            span,
            fps: span > 0 ? Math.round((sc.frames.length - 1) * 10000 / span) / 10 : 0,
        };
    }
}

