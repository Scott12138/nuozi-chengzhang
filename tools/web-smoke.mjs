// ------------------------------------------------------------
//  牌位是随机的（格点加权采样 + 抖动），脚本没有视觉识别能力，
//  所以让游戏在 DEBUG 模式把可点牌与坐标打出来，脚本照着点。
//  策略很朴素但够用：优先连点同一个牌面，因为那才有机会凑成「碰」。
// ------------------------------------------------------------

/** 取最近一条「可点」日志 */
function latestPickableLine(cdp) {
    for (let i = cdp.consoleLines.length - 1; i >= 0; i--) {
        if (cdp.consoleLines[i].includes('牌局 已清=')) return cdp.consoleLines[i];
    }
    return null;
}

/** 目前已收到的「牌局」日志条数 —— 用它判断"点击后游戏有没有吐出新状态" */
function pickableSeq(cdp) {
    let n = 0;
    for (const l of cdp.consoleLines) if (l.includes('牌局 已清=')) n++;
    return n;
}

/**
 * 等游戏吐出一条**新的**牌局日志（返回实际等待毫秒；超时返回 -1）。
 *
 * 【为什么不能只 sleep 一个固定时长 —— 踩过的坑】
 * 自动试玩的决策完全依赖控制台里的那份「可点牌位置列表」，而点击之后
 * 游戏要过「选中 180ms + 飞行 ≤300ms + 落位余量」才会打出下一条列表。
 * 如果不等新日志、只按固定间隔决策，读到的仍是**点击前**那份列表，
 * 于是会对着一张已经拿走的牌再点一次；而这一下会被游戏的 B7 逻辑
 * 判成"点错了、撤回"（这是设计行为，不是 bug），日志里就出现
 *     「拿牌 → 取消选中 → 拿牌 → 落位 → 落位放弃」
 * 的死循环。表现像游戏卡死，实际是测试脚本读了过期数据。
 * 有了这条等待，"点一次 → 等状态真的变了 → 再点下一次"，
 * 节奏自动跟真人对齐，也不会再产生无效点击。
 */
async function waitNewPickable(cdp, seqBefore, timeoutMs) {
    const t0 = Date.now();
    while (Date.now() - t0 < timeoutMs) {
        if (pickableSeq(cdp) > seqBefore) return Date.now() - t0;
        await sleep(40);
    }
    return -1;
}

/** 解析 'wan-1@-238,146 sou-3@-170,60' 这种串 */
function parsePickable(line) {
    const out = [];
    if (!line) return out;
    const re = /([a-z]+-\d+)@(-?\d+),(-?\d+)/g;
    let m;
    while ((m = re.exec(line)) !== null) {
        out.push({ key: m[1], x: Number(m[2]), y: Number(m[3]) });
    }
    return out;
}

// ------------------------------------------------------------
//  《挪字成章》专用的日志解析与拖拽自动试玩
// ------------------------------------------------------------
//  游戏侧每步都会打这四行（见 GamePage.diag）：
//    [Diag] BOARD cols=6 rows=5 pitch=112 cell=99 cx=0 cy=-130
//    [Diag] TILES 木@0,1,radical 仓@3,4,part …
//    [Diag] STATE seq=7 合成 步=3 已消=2/9 剩牌=17
//    [Diag] SUGGEST 从=木@1,2 到=2,2 命中=仓
//  脚本只依赖这些，不去"看"画面 —— 命令行下没有视觉识别能力。
// ------------------------------------------------------------

/**
 * 「当前这一局」的日志起点 = 最后一条切进对局页的日志的下标。
 *
 * 【为什么所有 diag 读取都要锚在这里 —— 一个真实的假失败】
 * 一轮冒烟里跑了 L1、L2 两局。L1 结束时 STATE 序号已经到 10，
 * L2 重新从 seq=1 开始。而原先 stateSeqOf 取的是**全历史最大值**，
 * 于是恒等于 10，"等序号 >10" 永远等不到 —— L2 的 9 步拖拽被整批
 * 误判成"状态没变"，可日志里 已消=1/9…9/9 一路在涨。
 * 同理，lastDiag 会返回**上一局**遗留的 BOARD / SUGGEST（L1 末尾的
 * "SUGGEST none" 正好会让解析拿到 null，看上去像"棋盘坏了"）。
 * 锚定之后，读到的一定是本局数据；本局还没打出来的，就诚实地返回 null。
 */
function gameAnchor(cdp) {
    for (let i = cdp.consoleLines.length - 1; i >= 0; i--) {
        if (cdp.consoleLines[i].includes('[PageManager] 进入页面 game')) return i;
    }
    return 0;
}

/** 取**本局**里最后一条含 needle 的日志行 */
function lastDiag(cdp, needle) {
    const start = gameAnchor(cdp);
    for (let i = cdp.consoleLines.length - 1; i >= start; i--) {
        if (cdp.consoleLines[i].includes(needle)) return cdp.consoleLines[i];
    }
    return null;
}

/** 解析 BOARD 行 → { cols, rows, pitch, cell, cx, cy } */
function parseBoardGeo(line) {
    if (!line) return null;
    const out = {};
    const body = line.slice(line.indexOf('BOARD') + 5);
    for (const kv of body.trim().split(/\s+/)) {
        const i = kv.indexOf('=');
        if (i > 0) out[kv.slice(0, i)] = Number(kv.slice(i + 1));
    }
    return Number.isFinite(out.pitch) ? out : null;
}

/**
 * 解析 FRAME 行 → { headY, ct, wrapTop, wrapH, boardH, boardTop, room, slack }
 * 单位一律是**设计单位（720 系）**，与棋盘几何同一口径 —— 别拿去和
 * `[Layout]` dump 的 372px 系混用（换算 ×1.9355，见文件头那条）。
 */
function parseFrame(line) {
    if (!line) return null;
    const out = {};
    const body = line.slice(line.indexOf('FRAME') + 5);
    for (const kv of body.trim().split(/\s+/)) {
        const i = kv.indexOf('=');
        if (i > 0) out[kv.slice(0, i)] = Number(kv.slice(i + 1));
    }
    return Number.isFinite(out.wrapH) ? out : null;
}

/**
 * 取页面**最后一次**版式转储 → `{ 块名: {x,y,w,h,db} }`（单位 = 372px 设计系）。
 *
 * 【为什么要"最后一段"，而不是全文扫描】
 *   `[Layout] game …` 一行一个块，一页一整套。同一轮里进两次对局页就有两套，
 *   按名字全局扫会拿到**上一套**的残留（例如上一关的 `.board-wrap`）——
 *   与 `lastDiag` 那个"跨局残留"是同一类坑。所以先定位最后一行，
 *   再向前收拢**连续**的同一页行，得到"这一套"。
 * ⚠️ 名字可能重复（两行 `.goal-chip[0]`），这里后写覆盖先写 ——
 *   本函数的消费方（frame 动作）只用唯一的块名，不受影响。
 */
/** 372px 设计稿 → 720 设计单位的比例（= CFG.SPEC.SCALE，与 px() 同源） */
const PX_SCALE = 720 / 372;

/**
 * 把 `[Layout]` 转储里的一个盒子（372px 系、自**屏幕左上角**）
 * 换算成**屏幕坐标**（CDP 点击用）。见 `lb:` 动作那段说明。
 * ⚠️ 两处偏移都要带：① `−UNIT_W/2` / `−UNIT_H/2`（设计单位的原点在屏幕中心）
 *    ② `cx` / `cy` 是画布中心 —— 少任何一处都是"差半屏"级的错。
 */
function dumpBoxToScreen(cx, cy, ps, b) {
    return {
        x: Math.round(cx + ps * (PX_SCALE * (b.x + b.w / 2) - UNIT_W / 2)),
        y: Math.round(cy + ps * (PX_SCALE * (b.y + b.h / 2) - UNIT_H / 2)),
    };
}

function layoutBlock(cdp, page = 'game') {
    const lines = cdp.consoleLines;
    const pre = `[Layout] ${page} `;
    let end = -1;
    for (let i = lines.length - 1; i >= 0; i--) {
        if (lines[i].includes(pre)) { end = i; break; }
    }
    if (end < 0) return null;
    let start = end;
    while (start - 1 >= 0 && lines[start - 1].includes(pre)) start--;
    const out = {};
    for (let i = start; i <= end; i++) {
        const m = lines[i].match(
            /\[Layout\]\s+\S+\s+(\S+)\s+x=(-?[\d.]+)\s+y=(-?[\d.]+)\s+w=(-?[\d.]+)\s+h=(-?[\d.]+)\s+db=(-?[\d.]+)/);
        if (!m) continue;
        out[m[1]] = { x: +m[2], y: +m[3], w: +m[4], h: +m[5], db: +m[6] };
    }
    return Object.keys(out).length ? out : null;
}

/** 解析 SUGGEST 行 → { char, fromR, fromC, toR, toC, hit } */
function parseSuggest(line) {
    if (!line || line.includes('SUGGEST none')) return null;
    const m = line.match(/从=(\S+?)@(\d+),(\d+)\s+到=(\d+),(\d+)\s+命中=(\S+)/);
    if (!m) return null;
    return { char: m[1], fromR: +m[2], fromC: +m[3], toR: +m[4], toC: +m[5], hit: m[6] };
}

/**
 * 解析 NONMATCH 行 → { char, fromR, fromC, toR, toC }
 * 语义：这是一步"玩家拖得到、但落位**凑不成字**"的走法 —— 严格回弹的样本。
 * 来源 Board.findNonMatch（种子固定，所以连续读到的都是同一步）。
 */
function parseNonMatch(line) {
    // 见下方实现（与 parseTreasure 同构）
    return parseFromTo(line, 'NONMATCH');
}

/**
 * 解析 TREASURE 行 → { char, hit, fromR, fromC, toR, toC, direct }
 * 语义：把两张同款宝牌凑到一起的走法。来源 Board.findTreasureMove / findDirectTreasure。
 *   · direct=false —— `TREASURE 从=铁砧@r,c 到=r,c 命中=铁砧`：**挪一步**（拖）
 *   · direct=true  —— `TREASURE direct 从=铁砧@r,c 到=r,c`：两张**已经对齐**，
 *                     该**点一下**（tapTile 直接消）而不是拖
 *   · 都没有       —— `TREASURE none`：这盘暂时既挪不到也点不到，
 *                     多半是两张宝牌之间夹着别的牌（先把中间那张消掉再说）
 * ★ 必须区分 direct —— 上一版只认"挪一步"，于是把"可以点掉"误判成
 *   "本关没有宝牌走法"，取证直接失败（2026-10-03 实测）。同 `REACH direct=` 的教训。
 */
function parseTreasure(line) {
    if (!line) return null;
    const direct = line.includes('TREASURE direct');
    const out = parseFromTo(line, 'TREASURE');
    if (!out) return null;
    out.direct = direct;
    return out;
}

/** NONMATCH / TREASURE 两行格式相同：`从=X@r,c 到=r,c[ 命中=Y]` */
function parseFromTo(line, tag) {
    if (!line || line.includes(tag + ' none')) return null;
    const m = line.match(/从=(\S+?)@(\d+),(\d+)\s+到=(\d+),(\d+)(?:\s+命中=(\S+))?/);
    if (!m) return null;
    return { char: m[1], fromR: +m[2], fromC: +m[3], toR: +m[4], toC: +m[5], hit: m[6] || '' };
}

/**
 * 解析 PUSH / PUSHNM 行 → 推箱走法。
 * 例：
 *   [Diag] PUSH   从=奴@0,0 到=0,1 推=革@0,1->0,2 命中=弓@1,1
 *   [Diag] PUSHNM 从=奴@0,0 到=1,0 推=父@1,0->2,0
 *
 * 语义（2026-10-03 推箱上线）：
 *   · PUSH    —— 推着相邻牌走、落位**凑成了字**。玩家关心的那句
 *                "被推的牌永久停在新位置"就断言在它上面。
 *   · PUSHNM  —— 推着相邻牌走、落位**凑不成字** → 整段沿原路弹回。
 *   · none    —— 本盘没有推箱走法（很常见，盘面小或牌挨得不巧）。**跳过，不算失败**。
 *
 * ★ `命中=X@r,c` 里的坐标是**推完之后的**：命中牌若也在被推之列，
 *   它落位后会被消掉（那时断言要按"已消失"处理），否则原地不动。
 *   这条区分不能省 —— 少了它，"被推的牌停在新位置"这句就只能弱化成
 *   "它要么在新位置、要么没了"，等于没断言。
 */
function parsePush(line, tag) {
    if (!line || line.includes(tag + ' none')) return null;
    const m = line.match(/从=(\S+?)@(\d+),(\d+)\s+到=(\d+),(\d+)\s+推=(\S+)(?:\s+命中=(\S+))?/);
    if (!m) return null;
    const shoved = m[6].split('|').map((s) => {
        const k = s.match(/^(\S+?)@(\d+),(\d+)->(\d+),(\d+)$/);
        return k ? { char: k[1], fromR: +k[2], fromC: +k[3], toR: +k[4], toC: +k[5] } : null;
    }).filter(Boolean);
    let hit = null;
    if (m[7]) {
        const h = m[7].match(/^(\S+?)@(\d+),(\d+)$/);
        if (h) hit = { char: h[1], r: +h[2], c: +h[3] };
    }
    return { char: m[1], fromR: +m[2], fromC: +m[3], toR: +m[4], toC: +m[5], shoved, hit };
}

/** 在 TILES 表里找一张「某字在某格」的牌 */
function tileAt(tiles, char, r, c) {
    return tiles.find((t) => t.char === char && t.r === r && t.c === c) || null;
}

/** 从最后一条 STATE 行里抠出 `剩牌=` —— 宝牌"额外消一对"的硬判据就用它 */
function remainOf(cdp) {
    const line = lastDiag(cdp, '[Diag] STATE');
    if (!line) return -1;
    const m = line.match(/剩牌=(\d+)/);
    return m ? Number(m[1]) : -1;
}

/**
 * 从最后一条 STATE 行里抠出 `已消=` 的**分子**（已消 X/Y 里的 X）。
 * 宝牌凑对时，"被送掉的那一对"必须计进它对应的字 —— 目标条分子要 +1。
 * 读不到返回 -1（调用方按"读不到"处理，别当 0）。
 */
function clearedOf(cdp) {
    const line = lastDiag(cdp, '[Diag] STATE');
    if (!line) return -1;
    const m = line.match(/已消=(\d+)\//);
    return m ? Number(m[1]) : -1;
}

/**
 * 解析 XFORM 行 → { x, y, scale, winW, winH }
 * 语义：**游戏自己**把「格 (0,0) 的中心」换算成的屏幕坐标（y 从屏幕顶往下）。
 * 它是"工装那套 cx + 设计x×PS"的对照组 —— 两边必须吻合，见 chaiziXformCheck。
 */
function parseXform(line) {
    if (!line) return null;
    const m = line.match(/XFORM cell=0,0 screen=(-?[\d.]+),(-?[\d.]+)\s+win=(\d+)×(\d+)\s+scale=([\d.]+)/);
    if (!m) return null;
    return { x: +m[1], y: +m[2], winW: +m[3], winH: +m[4], scale: +m[5] };
}

/**
 * 解析 REACH 行 → { direct, suggest }
 * 语义：把 `SUGGEST none` 的**歧义**拆开（这是 2026-10-02 那次"弹层怎么没弹"的产物）。
 *   · suggest=1        → 还有可挪的解法（正常）
 *   · direct=1 suggest=0 → 盘面还活着：有一对已经同行/同列相邻，**点**一下就能消。
 *                          findSuggest 只把**空格**当落点，所以"把 A 挪到 B 身上"
 *                          这种走法它永远给不出来 —— 这不是没解，是解法不叫"挪"。
 *   · direct=0 suggest=0 → 真的卡住，游戏此时会弹「看广告重排」。
 * 旧版游戏不打这一行（→ null），此时退回"等满 4s 就收工"的老行为。
 */
function parseReach(line) {
    if (!line) return null;
    const m = line.match(/REACH direct=(\d) suggest=(\d)/);
    if (!m) return null;
    return { direct: m[1] === '1', suggest: m[2] === '1' };
}

/** 解析 TILES 行 → [{ char, r, c, kind }]（顺序即游戏给的顺序） */
function parseTiles(line) {
    if (!line) return [];
    const at = line.indexOf('TILES');
    if (at < 0) return [];
    return line.slice(at + 5).trim().split(/\s+/).map((s) => {
        const m = s.match(/^(\S+)@(\d+),(\d+),(\S+)$/);
        return m ? { char: m[1], r: +m[2], c: +m[3], kind: m[4] } : null;
    }).filter(Boolean);
}

/** 本局 STATE 里的「步=」数（严格回弹后必须不变，所以它是个判据） */
function movesOf(cdp) {
    const line = lastDiag(cdp, '[Diag] STATE');
    if (!line) return -1;
    const m = line.match(/步=(\d+)/);
    return m ? Number(m[1]) : -1;
}

/**
 * 解析 `严格回弹：` / `回弹到位：` 行里的节点位置与目标位置。
 * 例：`[GamePage] 回弹到位：木 节点=(120,240) 目标=(120,240)`
 */
function parseXY(line) {
    if (!line) return null;
    const m = line.match(/节点=\((-?\d+),(-?\d+)\)\s+目标=\((-?\d+),(-?\d+)\)/);
    if (!m) return null;
    return { nx: +m[1], ny: +m[2], tx: +m[3], ty: +m[4] };
}

/** **本局**最大的 STATE 序号。-1 = 本局还没打出过 STATE（见 gameAnchor 的说明） */
function stateSeqOf(cdp) {
    const start = gameAnchor(cdp);
    let n = -1;
    for (let i = start; i < cdp.consoleLines.length; i++) {
        const m = cdp.consoleLines[i].match(/\[Diag\] STATE seq=(\d+)/);
        if (m) n = Math.max(n, Number(m[1]));
    }
    return n;
}

/** 等 STATE 序号超过 seqBefore（返回是否成功） */
async function waitState(cdp, seqBefore, timeoutMs) {
    const t0 = Date.now();
    while (Date.now() - t0 < timeoutMs) {
        if (stateSeqOf(cdp) > seqBefore) return true;
        await sleep(50);
    }
    return false;
}

/** 格子 → 棋盘局部坐标（与 GamePage.cellX / cellY 必须同口径） */
function cellLocalX(geo, c) { return (c - (geo.cols - 1) / 2) * geo.pitch; }
function cellLocalY(geo, r) { return ((geo.rows - 1) / 2 - r) * geo.pitch; }

// ------------------------------------------------------------
//  「多选配对」呼吸闪烁：取样本 + 断言（flash 动作用）
// ------------------------------------------------------------
/**
 * 解析一条 `[Diag] FLASH 中心=X@r,c 搭档数=N 搭档=Y@r,c Z@r,c …` 行。
 * （游戏侧的格式见 GamePage.refreshFlash；`FLASH none` 走 `isNone`。）
 * ⚠️ 搭档那一段没有 `搭档=` 这个前缀 —— 游戏打的是**空格分隔的裸列表**
 *    （`c.ps.map(p => `${p.char}@${p.r},${p.c}`).join(' ')`）。这里按
 *    "数出所有 `X@r,c` 形态的 token"来取，不依赖任何前缀，才不会因为
 *    游戏侧改了一句文案就静默退化成"0 个搭档"（那样断言会变成永远通过）。
 */
function parseFlashLine(line) {
    if (!line) return null;
    const sq = line.match(/FLASH\s+seq=(\d+)/);
    if (!sq) return null;                       // 没有 seq 认不出归属，按"格式不认识"处理
    const seq = +sq[1];
    if (line.includes('FLASH seq=' + seq + ' none')) return { isNone: true, seq, centers: [] };
    const m = line.match(/FLASH\s+seq=\d+\s+中心=(\S+?)@(\d+),(\d+)\s+搭档数=(\d+)\s*(.*)$/);
    if (!m) return null;
    const partners = [];
    const re = /(\S+?)@(\d+),(\d+)/g;
    let g;
    while ((g = re.exec(m[5])) !== null) {
        partners.push({ char: g[1], r: +g[2], c: +g[3] });
    }
    return {
        isNone: false,
        seq,
        center: { char: m[1], r: +m[2], c: +m[3] },
        declaredCount: +m[4],
        partners,
    };
}

/**
 * 取**当前盘面**的 `[Diag] FLASH` 样本。
 *
 * 【判据：seq 相等，不是"位置在 STATE 之后"】
 * 每行 FLASH 都自带 `seq=`（取自最近一次 `diag()`）。工装只认
 * **seq === 本局最后一条 STATE 的 seq** 的那些行 —— 这样"这批闪烁属于哪个盘面"
 * 是日志里写死的，不靠推断。
 * ★ 为什么不能用"STATE 之后的所有 FLASH 行"：洗牌那一路**整盘换位**，
 *   如果它不补 diag()，新盘的 FLASH 会顶着旧盘的 seq，两批样本就混成一批
 *   （旧盘的格在新盘上早就是别的字了，紧邻/TILES 断言会集体误报）。
 *   游戏侧已在 `reshuffleRemaining` 的 `settle()` 里补了 `diag('洗牌')`。
 */
function flashSamples(cdp) {
    const start = gameAnchor(cdp);
    let seq = -1;
    for (let i = cdp.consoleLines.length - 1; i >= start; i--) {
        const m = cdp.consoleLines[i].match(/\[Diag\] STATE seq=(\d+)/);
        if (m) { seq = Number(m[1]); break; }
    }
    if (seq < 0) return null;
    const out = [];
    for (let i = start; i < cdp.consoleLines.length; i++) {
        const line = cdp.consoleLines[i];
        if (!line.includes('[Diag] FLASH')) continue;
        const p = parseFlashLine(line);
        if (p && p.seq === seq) out.push({ i, line, p });
    }
    return out;
}

/**
 * 「多选配对」闪烁的硬断言（flash 动作的实现）。
 *
 * 【它防的是什么】
 * `refreshFlash()` 要挂在**每一个盘面变化点**上（开局 / 合成 / 宝牌 / 挪牌 /
 * 洗牌 / 复活），漏掉任何一处都不会报错、不会崩，只会"那个场景下不闪了" ——
 * 而"不闪"和"这个盘面本来就没有多选局面"在肉眼上完全一样。
 * 本断言的第一步（"最后一条 STATE 之后必须存在 FLASH 行"）就是专门堵这个的。
 *
 * 【它验不到什么（如实写明）】
 * "这两张真的能配对（canPair）"算不出来 —— 配对表在 TS 侧，工装只有日志。
 * 那半条由 core-selftest 的 `adjacentPairs` 断言兜底（它直接调 Board 的规则）。
 * 这里验的是**紧邻 + 数量自洽 + 与 TILES 对得上**，即用户原话的「左/右/上/下」。
 *
 * @returns {{ ok:number, fail:number, skipped:number, notes:string[] }}
 */
function chaiziFlashCheck(cdp) {
    const notes = [];
    const samples = flashSamples(cdp);
    if (!samples) {
        return { ok: 0, fail: 1, skipped: 0, notes: ['本局还没有任何 `[Diag] STATE` 行 —— 盘面还没就绪'] };
    }
    if (!samples.length) {
        // ★ 这条是**最要紧的那条**：盘面就绪了（有 STATE），却一条 FLASH 都没有
        //   ⇒ `refreshFlash()` 根本没被调到（漏挂 / 提前 return / 抛异常被吞）。
        return {
            ok: 0, fail: 1, skipped: 0,
            notes: ['当前盘面（最后一条 STATE 的 seq）**一条 `[Diag] FLASH` 都没有**'
                + ' —— refreshFlash() 没挂到这条路径上'],
        };
    }
    const bad = samples.filter((s) => !s.p);
    if (bad.length) {
        return {
            ok: 0, fail: 1, skipped: 0,
            notes: [`有 ${bad.length} 条 FLASH 行认不出格式（改名了？）：${bad[0].line}`],
        };
    }

    const nones = samples.filter((s) => s.p.isNone);
    const centers = samples.filter((s) => !s.p.isNone);
    if (nones.length && centers.length) {
        // 同一个盘面（seq 相同）里不可能既"有中心"又"没有" —— 只有一个解释：
        // 两次重算之间盘面被改过却没重新打 seq（调用点插在了 diag 之前）。
        return {
            ok: 0, fail: 1, skipped: 0,
            notes: [`同一个 seq 下既有 \`FLASH none\` 又有 \`中心=…\`（自相矛盾）`
                + ` —— 多半是 refreshFlash() 被插在了 diag() 之前`],
        };
    }
    if (!centers.length) {
        // `FLASH none` 是**合法**结果（这个盘面确实没有"一张牌挨着 ≥2 个能配的搭档"）。
        // 不算失败，但必须把"我这次什么都没验到"如实打出来 —— 不然它会冒充绿灯。
        return { ok: 0, fail: 0, skipped: 1, notes: ['本盘面是 `FLASH none`（没有多选局面）'] };
    }
    // ★ 同一个盘面可能被重算多次（拖动回弹 / 拖回原格都会重算，而盘面没变），
    //   于是同一批样本里会有**多行内容完全相同**的记录。去重后再报数 ——
    //   不去重的话输出会变成"中心 8 个"（其实是同一批 4 个报了两遍），
    //   判读的人会以为多选局面突然变多了。
    const uniq = [];
    const seenCenter = new Set();
    for (const s of centers) {
        const k = `${s.p.center.char}@${s.p.center.r},${s.p.center.c}`;
        if (!seenCenter.has(k)) { seenCenter.add(k); uniq.push(s); }
    }

    // 回查同一时刻的 TILES，用于"格上真的有这张牌、字也对"
    const tiles = parseTiles(lastDiag(cdp, '[Diag] TILES'));
    const at = (r, c, char) => tiles.some((t) => t.r === r && t.c === c && t.char === char);
    const occupied = (r, c) => tiles.some((t) => t.r === r && t.c === c);

    const problems = [];
    for (const s of uniq) {
        const p = s.p;
        const tag = `${p.center.char}@${p.center.r},${p.center.c}`;
        // ② 声明的数目 == 实际列出的个数
        if (p.declaredCount !== p.partners.length) {
            problems.push(`${tag}：搭档数写 ${p.declaredCount}，实际列了 ${p.partners.length} 张`);
        }
        // 判据下限：≥2 才算"多选"（只有 1 个搭档时没有选择可言，游戏不该闪）
        if (p.partners.length < 2) {
            problems.push(`${tag}：只列了 ${p.partners.length} 张搭档（多选至少要有 2 张）`);
        }
        if (tiles.length && !at(p.center.r, p.center.c, p.center.char)) {
            problems.push(`${tag}：中心格上不是「${p.center.char}」（TILES 里对不上）`);
        }
        for (const q of p.partners) {
            // ③ 四方向紧邻（用户原话「左/右/上/下」）—— 斜角和不挨着都不算
            const d = Math.abs(q.r - p.center.r) + Math.abs(q.c - p.center.c);
            if (d !== 1) {
                problems.push(`${tag} 的搭档「${q.char}」@${q.r},${q.c} 不紧邻（曼哈顿距离 ${d}）`);
            }
            if (tiles.length && !occupied(q.r, q.c)) {
                problems.push(`${tag} 的搭档格 ${q.r},${q.c} 上**没有牌**（TILES 里是空的）`);
            } else if (tiles.length && !at(q.r, q.c, q.char)) {
                problems.push(`${tag} 的搭档格 ${q.r},${q.c} 上是别的字（日志写「${q.char}」）`);
            }
        }
    }
    if (problems.length) {
        return { ok: 0, fail: 1, skipped: 0, notes: problems.slice(0, 5) };
    }
    notes.push(`seq=${centers[0].p.seq}，中心 ${uniq.length} 个：`
        + uniq.map((s) => `${s.p.center.char}@${s.p.center.r},${s.p.center.c}(${s.p.partners.length})`).join('、'));
    return { ok: uniq.length, fail: 0, skipped: 0, notes };
}

// ------------------------------------------------------------
//  页面状态判定（p: 断言用）
// ------------------------------------------------------------
//  来源：PageManager.goto 打印的 `[PageManager] 进入页面 <name>`。
//  这是**切页真的完成**之后才打的日志（在 page.build() 之后），
//  所以它比"某个节点存在"可靠 —— 节点可能还没建完，也可能建完又被销毁。
// ------------------------------------------------------------

/** 最后一条切页日志里的页面名（没有则空串） */
function pageOf(cdp) {
    for (let i = cdp.consoleLines.length - 1; i >= 0; i--) {
        const m = cdp.consoleLines[i].match(/\[PageManager\] 进入页面 (\S+)/);
        if (m) return m[1];
    }
    return '';
}

/** 等当前页面变成 want（返回 {ok, cur}） */
async function waitPage(cdp, want, timeoutMs) {
    const t0 = Date.now();
    let cur = pageOf(cdp);
    while (Date.now() - t0 < timeoutMs) {
        cur = pageOf(cdp);
        if (cur === want) return { ok: true, cur };
        await sleep(60);
    }
    return { ok: false, cur };
}

/** 最后一条 Toast 文案（没有则空串）。数据源见 ui/Toast.ts 的 show() */
/**
 * 最后一条 Toast 的文案。
 *
 * ⚠️⚠️ 正则里的 `[^\n]*` 不是笔误，**不能用 `.*$`** ⚠️⚠️
 *   本作的 Toast 大量是**两行**的（`'这一步凑不成字\n字牌已滑回原位'`、
 *   `'首版就到这里\n更多字正在路上'`……），而 `Runtime.consoleAPICalled`
 *   回传的是**一整条含换行的字符串**。JS 正则里 `.` 不匹配 `\n`，
 *   且没有 `m` 标志时 `$` 只匹配字符串末尾 —— 于是
 *   `/\[Toast\] (.*)$/` 对多行文案**整体匹配失败**（`.*` 停在 `\n` 前、`$` 又对不上），
 *   表现为"这条提示从没弹过"，而它其实刚刚弹过。
 *   2026-10-02 实测踩到：`t:首版就到这里` 报「没有弹出任何提示」，
 *   而同一份 console.log 里 `[log] [Toast] 首版就到这里\n更多字正在路上` 白纸黑字写着。
 *   → 只取**第一行**（`[^\n]*`）即可：断言用的都是第一行里的关键词。
 */
function toastOf(cdp) {
    for (let i = cdp.consoleLines.length - 1; i >= 0; i--) {
        const m = cdp.consoleLines[i].match(/\[Toast\] ([^\n]*)/);
        if (m) return m[1].trim();
    }
    return '';
}

/**
 * 本局**曾经**弹过的全部 Toast 文案（用 `\n` 连接）。
 * 与 toastOf 的区别：后者只看最后一条，连续两句话时第一句会被顶掉 —— 见 `th:` 的说明。
 * ⚠️ 正则与 toastOf 同源，多行文案同样只取第一行（理由见上）。
 */
function toastsAll(cdp) {
    const out = [];
    const start = gameAnchor(cdp);
    for (let i = start; i < cdp.consoleLines.length; i++) {
        const m = cdp.consoleLines[i].match(/\[Toast\] ([^\n]*)/);
        if (m) out.push(m[1].trim());
    }
    return out.join('\n');
}

/**
 * 本局弹层弹出过的标题列表。
 * 数据源见 ui/AdGate.ts / ui/FailGate.ts 的 log —— **两个弹层的日志格式是刻意同构的**
 * （都是 `[<组件>] 弹出：<标题> / <按钮>`），所以一条正则同时覆盖：
 *   「卡住了」（死局重排，AdGate）与「时间到了」（复活，FailGate）。
 */
function gatesOf(cdp) {
    const out = [];
    const start = gameAnchor(cdp);
    for (let i = start; i < cdp.consoleLines.length; i++) {
        const m = cdp.consoleLines[i].match(/\[(?:AdGate|FailGate)\] 弹出：(.+?)\s*\/\s*/);
        if (m) out.push(m[1].trim());
    }
    return out;
}

/**
 * ★ 坐标基准自检：游戏算一遍、工装算一遍，两边必须吻合。
 *
 * 【为什么需要它】
 * 2026-10-02 惨过一次：日志里 SUGGEST 明写格 (0,0)，游戏却收到格 (2,0) ——
 * 差**恰好两行**（224 设计单位）。表现是"拖拽完全没反应"，而报错信息全指错方向。
 * 逐项核对 `getUILocation → convertToNodeSpaceAR` 之后才确认：**游戏侧完全正确**，
 * 偏差在工装这侧。可当时产物里没有任何一条能"当场"分辨是谁错 —— 只能靠手算。
 *
 * 现在这条自检把这层不确定性砍掉了：
 *   · 游戏从自己的变换链算出「格 (0,0) 中心的屏幕坐标」→ `[Diag] XFORM`
 *   · 工装用自己那套（cx + 设计x × PS）再算一遍
 *   · 两者差 > 3px 就**当场失败**，并直接指出是工装的问题
 * 下次再遇到"拖了没反应"，这条断言会先跳出来，不必再去翻游戏代码。
 *
 * @returns {{ok:boolean, dx:number, dy:number, gx?:number, gy?:number, hx?:number, hy?:number, why?:string}}
 */
function chaiziXformCheck(cdp, cx, cy) {
    const x = parseXform(lastDiag(cdp, '[Diag] XFORM'));
    const geo = parseBoardGeo(lastDiag(cdp, '[Diag] BOARD'));
    if (!x || !geo) return { ok: false, dx: 0, dy: 0, why: '还没拿到 XFORM 或 BOARD' };
    // 工装那套：格 (0,0) 中心 = 棋盘中心 + 格内偏移 → 屏幕
    const dxDesign = geo.cx + cellLocalX(geo, 0);
    const dyDesign = geo.cy + cellLocalY(geo, 0);
    const hx = cx + dxDesign * PS;
    const hy = cy - dyDesign * PS;
    const dx = x.x - hx, dy = x.y - hy;
    return {
        ok: Math.abs(dx) <= 3 && Math.abs(dy) <= 3,
        dx, dy, gx: x.x, gy: x.y, hx, hy,
        why: '',
    };
}

/**
 * 「点掉已对齐的一对」—— drag 循环的兜底动作。
 *
 * 【为什么单纯拖是不够的】
 * 玩法有两条达成路径：**拖**（挪到同行/同列的落点）与**点**（两张牌本来就同行或
 * 同列、中间无阻挡，点任一张即合成）。而 findSuggest 的候选落点只取空格，
 * 所以"已经对齐、只差点一下"的局面在它眼里等于无解 —— SUGGEST 会给 none，
 * 但游戏自己**没有卡住**（checkDeadlock 里 hasDirectMatch 会提前放行）。
 *
 * 冒烟的 drag 循环原先只认 SUGGEST，碰到这种局面就直接收工，
 * 于是「卡住弹层」的断言误报失败（2026-10-02 实际发生）。
 *
 * 【做法】不去猜哪两张能配（那要复刻玩法规则），而是**逐个点一遍场上的非干扰牌**，
 * 每点一张就看 STATE 序号涨没涨 —— 涨了说明点对了。代价最多 = 剩余牌数 次点击，
 * 且只在"没有可挪的解法"时才走这条路。
 *
 * @returns 被点中而触发合成的牌，或 null（点了一整轮状态都没动 = 真的卡住）
 */
async function chaiziTapDirect(cdp, cx, cy, geo) {
    const ts = parseTiles(lastDiag(cdp, '[Diag] TILES')).filter((t) => t.kind !== 'junk');
    for (const t of ts) {
        const dx = geo.cx + cellLocalX(geo, t.c);
        const dy = geo.cy + cellLocalY(geo, t.r);
        const seq0 = stateSeqOf(cdp);
        console.log(`       点一下「${t.char}」(${t.r},${t.c}) 设计(${Math.round(dx)},${Math.round(dy)})`);
        await cdp.clickAt(cx + dx * PS, cy - dy * PS);
        if (await waitState(cdp, seq0, 900)) return t;
    }
    return null;
}

/**
 * 自动拖拽 n 步：每步读 SUGGEST → 派真事件拖过去 → 等 STATE 序号变大。
 * @returns {{ok:number, fail:number}} 状态真的变了的步数 / 没变的步数
 */
async function chaiziDragPlay(cdp, cx, cy, steps, gapMs = 420) {
    let ok = 0, fail = 0;
    // ---- 开拖之前先校准坐标基准（见 chaiziXformCheck 的说明）----
    {
        const xs = chaiziXformCheck(cdp, cx, cy);
        if (xs.ok) {
            console.log(`    坐标基准自检 ✅ 格(0,0) 游戏(${xs.gx.toFixed(1)},${xs.gy.toFixed(1)})`
                + ` vs 工装(${xs.hx.toFixed(1)},${xs.hy.toFixed(1)})，差 (${xs.dx.toFixed(1)},${xs.dy.toFixed(1)})`);
        } else if (xs.gx === undefined) {
            console.log(`    ⚠ 坐标基准自检跳过：${xs.why}`);
        } else {
            const msg = `坐标基准自检失败：格(0,0) 游戏算 ${xs.gx.toFixed(1)},${xs.gy.toFixed(1)}，`
                + `工装算 ${xs.hx.toFixed(1)},${xs.hy.toFixed(1)}，差 (${xs.dx.toFixed(1)},${xs.dy.toFixed(1)})px`
                + ' —— 这是**工装**的 cx/cy/PS 与实际不符，先查这里，别去翻游戏代码';
            FAILURES.push(msg);
            console.log(`    ❌ ${msg}`);
        }
    }
    // 「同一个建议连续失败」的计数：严格回弹下 SUGGEST 一定是"挪过去立刻能合成"的走法，
    // 同一个建议失败两次以上只可能有两种原因 —— 坐标换算不符，或 findSuggest 不可执行。
    // 两种都不能让它悄悄过去（上一轮就是这样：4 步成功、35 步空耗，脚本照样报"通过"）。
    let lastKey = '', dupFail = 0;
    for (let s = 0; s < steps; s++) {
        // 【护栏：本关已结束就收手】
        //  drag:<n> 里的 n 是"最多拖几步"。若通关后仍继续，脚本读到的是**最后一帧**
        //  的 BOARD/SUGGEST 日志（通关后不再更新），于是会拿着已经用过的坐标
        //  空拖到底 —— 每一下都"状态没变"，最后把 fail 堆成一串假失败。
        //  判据用两条：① 已离开对局页（PageManager 切页日志）；② 最后一条 STATE 是「通关」。
        if (pageOf(cdp) !== 'game') {
            console.log(`    （已离开对局页，提前结束；共拖 ${s} 步）`);
            break;
        }
        const stNow = lastDiag(cdp, '[Diag] STATE');
        if (stNow && stNow.includes('通关')) {
            console.log(`    （本关已通关，提前结束；共拖 ${s} 步）`);
            break;
        }
        // 【护栏：进关后别抢跑】
        //  贴图是异步资源（TileAtlas 一张一张 resources.load），而 BOARD/SUGGEST
        //  这两行日志要等棋盘建好才打。刚切进对局页就立刻读，必然读不到 ——
        //  若这时直接 break，drag 就会"零步结束"，看起来像"事件层坏了"。
        //  所以这里做**有界等待**：等到齐就走，等不到才放弃。
        let geo = null, sug = null, reach = null;
        {
            const tw = Date.now();
            while (Date.now() - tw < 4000) {
                geo = parseBoardGeo(lastDiag(cdp, '[Diag] BOARD'));
                sug = parseSuggest(lastDiag(cdp, '[Diag] SUGGEST'));
                reach = parseReach(lastDiag(cdp, '[Diag] REACH'));
                if (geo && sug) break;
                // 知道了"这不是可挪的解法"就不必干等 —— 要么去点、要么已经卡住。
                // （旧版游戏不打 REACH → reach 恒为 null → 退回原来的等满 4s）
                if (geo && reach) break;
                if (pageOf(cdp) !== 'game') break;   // 等的过程里被切走了就别等了
                await sleep(100);
            }
        }
        if (geo && !sug) {
            // ★ 这里必须**先分辨**再下结论：SUGGEST none 不等于"卡住"。
            if (reach && reach.direct) {
                console.log('    （没有可挪的解法，但有一对已对齐 → 改成点掉它）');
                const hit = await chaiziTapDirect(cdp, cx, cy, geo);
                if (hit) {
                    ok++;
                    lastKey = ''; dupFail = 0;
                    console.log(`       点中了「${hit.char}」；状态：${lastDiag(cdp, '[Diag] STATE')}`);
                    await sleep(gapMs);
                    continue;
                }
                const msg = '盘面上有已对齐的一对（REACH direct=1），但逐个点过去状态都不变'
                    + ' —— 点/拖两条路径都推不动，是真的坏了';
                FAILURES.push(msg);
                console.log(`       ❌ ${msg}`);
                break;
            }
            if (reach && !reach.suggest) {
                console.log('    （REACH direct=0 suggest=0 → 真的卡住，等游戏弹「看广告重排」）');
                break;
            }
            console.log('    （等 4s 仍拿不到棋盘几何或下一步建议，结束）');
            break;
        }
        if (!geo || !sug) {
            console.log('    （等 4s 仍拿不到棋盘几何或下一步建议，结束）');
            break;
        }
        const fromDX = geo.cx + cellLocalX(geo, sug.fromC);
        const fromDY = geo.cy + cellLocalY(geo, sug.fromR);
        const toDX = geo.cx + cellLocalX(geo, sug.toC);
        const toDY = geo.cy + cellLocalY(geo, sug.toR);
        const seq0 = stateSeqOf(cdp);
        console.log(`    [${s + 1}] 拖「${sug.char}」(${sug.fromR},${sug.fromC}) → (${sug.toR},${sug.toC})`
            + ` 设计(${Math.round(fromDX)},${Math.round(fromDY)}) → (${Math.round(toDX)},${Math.round(toDY)})`);
        // 设计坐标 → 屏幕坐标：原点=画布中心，乘 PS 换算到屏幕 px，且 y 轴相反
        await cdp.dragAt(cx + fromDX * PS, cy - fromDY * PS,
            cx + toDX * PS, cy - toDY * PS, 10);
        const changed = await waitState(cdp, seq0, 3000);
        const key = `${sug.fromR},${sug.fromC}>${sug.toR},${sug.toC}`;
        if (changed) {
            ok++;
            lastKey = ''; dupFail = 0;
            console.log(`       状态：${lastDiag(cdp, '[Diag] STATE')}`);
        } else {
            fail++;
            console.log('       ⚠ 拖完了但状态没变 —— 事件没接上，或落点判定不对');
            // 抓一条"实际抓到了哪张牌"的线索：严格回弹会把它打出来。
            // 若实际抓的牌 ≠ 建议的牌，说明坐标落到了别的格上（工装侧换算不符）。
            const rb = lastDiag(cdp, '[GamePage] 严格回弹：');
            const grab = rb ? rb.replace(/^.*严格回弹：/, '').split(' ')[0] : '';
            if (grab && grab !== sug.char) {
                console.log(`       ⚠ 实际抓到的牌是「${grab}」，建议的是「${sug.char}」`
                    + ' —— 坐标落到了别的格上（先查工装的 cx/cy/PS）');
            }
            dupFail = (key === lastKey) ? dupFail + 1 : 1;
            lastKey = key;
            if (dupFail >= 2) {
                const msg = `同一个建议连续 ${dupFail} 次拖不动：`
                    + `「${sug.char}」(${sug.fromR},${sug.fromC}) → (${sug.toR},${sug.toC})`
                    + ' —— 严格回弹下 SUGGEST 必然可执行，连续失败说明坐标换算或 findSuggest 有问题';
                FAILURES.push(msg);
                console.log(`       ❌ ${msg}`);
                break;
            }
        }
        await sleep(gapMs);
    }
    return { ok, fail };
}

/**
 * 严格回弹的硬断言：按 `[Diag] NONMATCH` 拖一次"凑不成字"的走法，
 * 验证牌**弹回原格**且盘面/步数不变。
 *
 * 【四条判据为什么一条都不能省】（详见 parseAction 里 `rebound:` 的说明）
 *   ① `严格回弹：` 出现 —— 证明判定确实走了这条路；
 *   ② `回弹到位：` 里「节点 == 目标」—— 证明位置真的还原了（不是"看起来在"）；
 *   ③ `[Diag] STATE seq` 不变 —— 证明**没有落子**。这条最关键：
 *      "先落子、再判消、消不了再挪回来"的旧写法会让 seq 涨一格，
 *      而画面上最后是平的，光看截图根本分辨不出来；
 *   ④ `步=` 不变 —— 弹回来的一步不该计入步数。
 * @returns {{ok:number, fail:number, skipped:number}}
 */
async function chaiziReboundTest(cdp, cx, cy, times) {
    let ok = 0, fail = 0, skipped = 0;
    for (let s = 0; s < times; s++) {
        if (pageOf(cdp) !== 'game') {
            console.log(`    （不在对局页，提前结束；共测 ${s} 次）`);
            break;
        }
        // 有界等待几何与样本就绪（贴图/棋盘是异步建的，刚进关读不到）
        let geo = null, nm = null;
        {
            const tw = Date.now();
            while (Date.now() - tw < 4000) {
                geo = parseBoardGeo(lastDiag(cdp, '[Diag] BOARD'));
                nm = parseNonMatch(lastDiag(cdp, '[Diag] NONMATCH'));
                if (geo && nm) break;
                if (pageOf(cdp) !== 'game') break;
                await sleep(100);
            }
        }
        if (!geo) {
            fail++;
            console.log('    ❌ 拿不到棋盘几何，无法做回弹断言');
            continue;
        }
        if (!nm) {
            // "每一步都能成字"是合法盘面（Board.findNonMatch 返回 null），
            // 只是这盘没有可回弹的样本 —— 算跳过，不算失败，更不能静默当成功。
            skipped++;
            console.log('    （本盘每一步都能凑成字，没有可回弹的走法 —— 跳过）');
            break;
        }

        const fromDX = geo.cx + cellLocalX(geo, nm.fromC);
        const fromDY = geo.cy + cellLocalY(geo, nm.fromR);
        const toDX = geo.cx + cellLocalX(geo, nm.toC);
        const toDY = geo.cy + cellLocalY(geo, nm.toR);
        const seq0 = stateSeqOf(cdp);
        const moves0 = movesOf(cdp);
        const mark = cdp.consoleLines.length;          // 只看这次拖动之后新增的日志
        console.log(`    [${s + 1}] 回弹测试：拖「${nm.char}」(${nm.fromR},${nm.fromC}) → `
            + `(${nm.toR},${nm.toC})　设计(${Math.round(fromDX)},${Math.round(fromDY)}) → `
            + `(${Math.round(toDX)},${Math.round(toDY)})`);

        // 真事件：mousePressed → mouseMoved ×N → mouseReleased
        await cdp.dragAt(cx + fromDX * PS, cy - fromDY * PS,
            cx + toDX * PS, cy - toDY * PS, 10);

        // 等补间跑完（REBOUND_MS=170 + 30ms 释放 _busy）+ 余量
        await sleep(900);

        const added = cdp.consoleLines.slice(mark);
        const rbLine = added.find((l) => l.includes('严格回弹：'));
        const backLine = added.filter((l) => l.includes('回弹到位：')).pop();
        const xy = parseXY(backLine);
        const seqSame = stateSeqOf(cdp) === seq0;
        const movesSame = movesOf(cdp) === moves0;

        const problems = [];
        if (!rbLine) problems.push('没有 `严格回弹：` 日志（这一手被当成了合法落子？）');
        if (!backLine) problems.push('没有 `回弹到位：` 日志（动画没跑完或牌没回位）');
        else if (!xy) problems.push('`回弹到位：` 行解析不出位置');
        else if (xy.nx !== xy.tx || xy.ny !== xy.ty) {
            problems.push(`牌没回到原位：节点(${xy.nx},${xy.ny}) ≠ 目标(${xy.tx},${xy.ty})`);
        }
        if (!seqSame) problems.push(`STATE seq 变了（${seq0} → ${stateSeqOf(cdp)}）—— 说明这一步被当成落子记了一笔`);
        if (!movesSame) problems.push(`步数变了（${moves0} → ${movesOf(cdp)}）—— 弹回的一步不该计入`);

        if (problems.length === 0) {
            ok++;
            console.log(`       ✅ 已回弹到原位（节点(${xy.nx},${xy.ny}) == 目标(${xy.tx},${xy.ty})）`
                + `，STATE seq=${seq0} 与 步=${moves0} 均未变`);
        } else {
            fail++;
            for (const p of problems) console.log(`       ❌ ${p}`);
        }
    }
    return { ok, fail, skipped };
}

/**
 * 推箱机制的硬断言（2026-10-03 加）。一轮里跑两条：
 *   A. 推 + 凑成字 → 被推的牌**永久停在新位置**；
 *   B. 推 + 凑不成字 → 整段**沿原路弹回**（盘面逐字不变、步数不变）。
 *
 * 样本取自游戏打印的 `[Diag] PUSH` / `[Diag] PUSHNM`（Board.findPush，种子固定）。
 * ⚠️ 两条都可能没有样本 —— 那是**跳过**，不是失败。详见 parseAction 里 `push:` 的说明。
 * @returns {{ok:number, fail:number, skipped:number}}
 */
async function chaiziPushTest(cdp, cx, cy, times) {
    let ok = 0, fail = 0, skipped = 0;

    /**
     * 等棋盘几何 + 指定那行样本就绪（贴图 / 棋盘是异步建的，刚进关读不到）。
     *
     * ⚠️ `needle` 与 `tag` 必须分开传，不能写成 `'[Diag] ' + tag`：
     *    `lastDiag` 是**从后往前找第一个包含 needle 的行**，而 `[Diag] PUSHNM …`
     *    里就含有 `[Diag] PUSH` 这个子串 —— 那一版会让 A 段（推 + 凑成字）
     *    读到 PUSHNM 的样本（没有「命中=」，被推的那串落位后根本没合成），
     *    断言从此变成一个"永远不成立"的假失败。所以 PUSH 的 needle 必须带尾随空格。
     */
    const awaitGeo = async (needle, tag) => {
        const tw = Date.now();
        while (Date.now() - tw < 4000) {
            const geo = parseBoardGeo(lastDiag(cdp, '[Diag] BOARD'));
            const smp = parsePush(lastDiag(cdp, needle), tag);
            if (geo && smp) return { geo, smp };
            if (pageOf(cdp) !== 'game') break;
            await sleep(100);
        }
        return { geo: parseBoardGeo(lastDiag(cdp, '[Diag] BOARD')), smp: null };
    };

    for (let s = 0; s < times; s++) {
        if (pageOf(cdp) !== 'game') {
            console.log(`    （不在对局页，提前结束；共测 ${s} 轮）`);
            break;
        }

        // ---------- A. 推 + 凑成字 ----------
        {
            // ⚠️ 这里**必须** `await` —— awaitGeo 是异步的（它要轮询等棋盘建好），
            //    少写一个 await，解构得到的是 Promise 本身，geo/smp 恒为 undefined，
            //    于是每一轮都报「拿不到棋盘几何」。这个坑 2026-10-03 实际踩到过一次：
            //    表现极具误导性 —— 同一时刻直接调 parseBoardGeo 明明是好的。
            const { geo, smp } = await awaitGeo('[Diag] PUSH ', 'PUSH');
            if (!geo) {
                fail++;
                console.log('    ❌ 拿不到棋盘几何，无法做推箱断言');
                continue;
            }
            if (!smp) {
                skipped++;
                console.log('    （本盘没有"推着走且凑成字"的走法 —— 跳过 A）');
            } else {
                const moves0 = movesOf(cdp), cleared0 = clearedOf(cdp);
                console.log(`    [${s + 1}]A 推箱合成：拖「${smp.char}」(${smp.fromR},${smp.fromC}) → `
                    + `(${smp.toR},${smp.toC})，被推 `
                    + smp.shoved.map((m) => `${m.char}@${m.fromR},${m.fromC}→${m.toR},${m.toC}`).join('、'));

                const fromDX = geo.cx + cellLocalX(geo, smp.fromC);
                const fromDY = geo.cy + cellLocalY(geo, smp.fromR);
                const toDX = geo.cx + cellLocalX(geo, smp.toC);
                const toDY = geo.cy + cellLocalY(geo, smp.toR);
                await cdp.dragAt(cx + fromDX * PS, cy - fromDY * PS,
                    cx + toDX * PS, cy - toDY * PS, 10);
                await sleep(1100);

                const tiles1 = parseTiles(lastDiag(cdp, '[Diag] TILES'));
                const moves1 = movesOf(cdp), cleared1 = clearedOf(cdp);
                const problems = [];
                if (moves1 !== moves0 + 1) {
                    problems.push(`步数应为 ${moves0 + 1}，实际 ${moves1}`);
                }
                if (cleared1 !== cleared0 + 1) {
                    problems.push(`已消应为 ${cleared0 + 1}，实际 ${cleared1}（这一手没合成？）`);
                }
                for (const m of smp.shoved) {
                    // 命中牌若正好是被推的那张，它落位后就被消掉了 —— 按"已消失"判
                    const eaten = smp.hit && smp.hit.r === m.toR && smp.hit.c === m.toC;
                    const got = tileAt(tiles1, m.char, m.toR, m.toC);
                    const stillAtFrom = tileAt(tiles1, m.char, m.fromR, m.fromC);
                    if (eaten) {
                        if (got) problems.push(`「${m.char}」本该在落位被消掉，却还留在 (${m.toR},${m.toC})`);
                    } else if (!got) {
                        problems.push(`「${m.char}」没停在新位置 (${m.toR},${m.toC})`
                            + (stillAtFrom ? '（还留在原格 —— 整段被弹回了？）' : '（不见了）'));
                    }
                }
                if (problems.length === 0) {
                    ok++;
                    console.log(`       ✅ 被推的 ${smp.shoved.length} 张全部停在新位置`
                        + `（${smp.shoved.map((m) => `${m.char}@${m.toR},${m.toC}`).join('、')}）`
                        + `，步数 ${moves0}→${moves1}，已消 ${cleared0}→${cleared1}`);
                } else {
                    fail++;
                    for (const p of problems) console.log(`       ❌ ${p}`);
                }
            }
        }

        // ---------- B. 推 + 凑不成字 → 整段回弹 ----------
        //   ⚠️ 必须**重新读** PUSHNM 行：A 那一手已经把盘面改了，
        //      沿用 A 之前读到的样本会拖到一个已经不对的格子上。
        {
            const { geo, smp } = await awaitGeo('[Diag] PUSHNM', 'PUSHNM');
            if (!geo || !smp) {
                skipped++;
                console.log('    （本盘没有"推着走且凑不成字"的走法 —— 跳过 B）');
                break;
            }
            const moves0 = movesOf(cdp);
            const tiles0 = parseTiles(lastDiag(cdp, '[Diag] TILES'));
            const mark = cdp.consoleLines.length;
            console.log(`    [${s + 1}]B 推箱回弹：拖「${smp.char}」(${smp.fromR},${smp.fromC}) → `
                + `(${smp.toR},${smp.toC})，被推 `
                + smp.shoved.map((m) => `${m.char}@${m.fromR},${m.fromC}→${m.toR},${m.toC}`).join('、'));

            const fromDX = geo.cx + cellLocalX(geo, smp.fromC);
            const fromDY = geo.cy + cellLocalY(geo, smp.fromR);
            const toDX = geo.cx + cellLocalX(geo, smp.toC);
            const toDY = geo.cy + cellLocalY(geo, smp.toR);
            await cdp.dragAt(cx + fromDX * PS, cy - fromDY * PS,
                cx + toDX * PS, cy - toDY * PS, 10);
            await sleep(900);

            const added = cdp.consoleLines.slice(mark);
            const rbLine = added.find((l) => l.includes('严格回弹：'));
            const tiles1 = parseTiles(lastDiag(cdp, '[Diag] TILES'));
            const moves1 = movesOf(cdp);
            const problems = [];
            if (!rbLine) problems.push('没有 `严格回弹：` 日志（这一手被当成了合法落子？）');
            if (moves1 !== moves0) problems.push(`步数变了（${moves0} → ${moves1}）—— 弹回的一步不该计入`);
            // 整段回弹的判据：盘面**逐字**还原（比顺序无关的集合）
            const sig = (a) => a.map((t) => `${t.char}@${t.r},${t.c},${t.kind}`).sort().join(' ');
            if (sig(tiles1) !== sig(tiles0)) {
                const bad = smp.shoved.filter((m) => !tileAt(tiles1, m.char, m.fromR, m.fromC));
                problems.push(`盘面没还原：${bad.length
                    ? `被推的 ${bad.map((m) => `「${m.char}」`).join('')}没回到原格`
                    : 'TILES 与拖动前不一致'}`);
            }
            if (problems.length === 0) {
                ok++;
                console.log(`       ✅ 整段 ${smp.shoved.length} 张全部回到原格，步数仍为 ${moves0}`);
            } else {
                fail++;
                for (const p of problems) console.log(`       ❌ ${p}`);
            }
        }
    }
    return { ok, fail, skipped };
}

/**
 * 解析一行 `[Diag] DRAG`（拖动过程中的逐格取样）。
 *
 * 行格式（由 GamePage.onMove 打印）：
 *   [Diag] DRAG 字=革 格=2,1 节点=(0,-112) 期望=(0,-112) 角度=0.00
 *   字     = 被拖的牌面
 *   格     = 当前落点格（行,列）
 *   节点   = 被拖那张牌的**实际节点位置**（棋盘局部坐标，设计单位）
 *   期望   = 那一格的**格心**（游戏自己用 cellX / cellY 算出来的）
 *   角度   = 节点旋转角（度）
 *
 * ★ 这一行只在**跨格**时打印（位置也只在跨格时变，所以这几行已经覆盖了整段拖动
 *   的全部取值；逐帧打会把归档的 console.log 淹掉 —— 一次拖动有几百帧）。
 * ★ 它是"拖动中牌是否落在格心 / 有没有歪 / 有没有出界"三件事的**唯一可测入口**。
 *   松手之后的那些断言（rebound / push）都只看终局，正是这个盲区让三个手感问题
 *   一路活到了真机试玩。
 */
function parseDrag(line) {
    if (!line || !line.includes('[Diag] DRAG')) return null;
    const m = line.match(/字=(\S+)\s+格=(\d+),(\d+)\s+节点=\((-?\d+),(-?\d+)\)\s+期望=\((-?\d+),(-?\d+)\)\s+角度=(-?[\d.]+)/);
    if (!m) return null;
    return {
        char: m[1], r: +m[2], c: +m[3],
        nx: +m[4], ny: +m[5], ex: +m[6], ey: +m[7], angle: +m[8],
    };
}

/**
 * 取**最新一个完整的 diag 快照**（同一盘的 BOARD / TILES / STATE / SUGGEST 一起返回）。
 *
 * 【为什么必须"整盘一起取"，而不是每样各取一条】
 * 游戏一次 dump 的打印顺序是**固定**的（见 GamePage 的 dumpDiag）：
 *   BOARD → TILES → STATE → SUGGEST → REACH → DIRECT → NONMATCH → PUSH → PUSHNM → TREASURE
 * 而 CDP 是**逐行**送达的。所以任何时刻都可能停在"这一盘只打了一半"的位置，
 * 于是分别调 `lastDiag('TILES')` / `lastDiag('SUGGEST')` 会拿到**两盘混起来的**数据 ——
 * 而这种"混盘"组合恰好能骗过所有基于内容的自洽检查（两边都旧、彼此自洽）。
 * ⇒ 判据是"从最后一条 BOARD 起、到下一盘之前"这一段，缺任何一样就算**这一盘还没打完**。
 *
 * 【返回 null 的含义】拿不到完整一盘的样本 —— 调用方应当**等**，而不是拿旧数据凑合。
 */
function lastDiagPass(cdp) {
    const start = gameAnchor(cdp);
    let i0 = -1;
    for (let i = cdp.consoleLines.length - 1; i >= start; i--) {
        if (cdp.consoleLines[i].includes('[Diag] BOARD')) { i0 = i; break; }
    }
    if (i0 < 0) return null;
    const seg = cdp.consoleLines.slice(i0);
    const pick = (needle) => seg.find((l) => l.includes(needle)) || null;
    const geoLine = pick('[Diag] BOARD');
    const tilesLine = pick('[Diag] TILES');
    const stateLine = pick('[Diag] STATE');
    const sugLine = pick('[Diag] SUGGEST');
    if (!geoLine || !tilesLine || !stateLine || !sugLine) return null;   // 这一盘还没打完
    const m = stateLine.match(/seq=(\d+)/);
    return { geoLine, tilesLine, stateLine, sugLine, seq: m ? Number(m[1]) : -1 };
}

/**
 * 等**比 `seqBefore` 更新的一整盘**打出来（返回那一盘；超时则返回当前那一盘）。
 *
 * 【它修的是哪一类假红 —— 三版修法，前两版都是错的，全部留档】
 * 症状：间歇性报"整段拖动一条 DRAG 行都没打"，6 轮里挂 1 轮，复跑又全绿。
 * 真因：`lastDiag(cdp, needle)` 是"**最后一条**含 needle 的行"，**不区分是哪一盘的**。
 *   上一手消掉牌之后，新盘的 SUGGEST 还没打出来就读它 ⇒ 拿到**上一盘**的走法；
 *   照着它拖 = 按在一个**已经空掉**的格子上 ⇒ `onDown` 找不到牌 ⇒ 零 DRAG 行。
 *   ★ 触发条件是**宝牌成对**那一手：它是**链式延迟结算**的（本体 + 额外送掉一对），
 *     实测**超过 700ms** 新的 STATE/SUGGEST 才落盘 —— 所以"拖动后 sleep 700ms"
 *     这种按时间猜的等待必然会漏。
 *
 * ⚠️ 第一版修法（按"控制台行号 >= 某个 mark"判定）是错的：
 *    mark 记在"取样**之前**"，于是**取样过程中才到达**的那条 SUGGEST 也算"新行"，
 *    下一轮等它时立刻假通过。6 轮里仍会挂 1 轮。
 * ⚠️ 第二版修法（等"最后那条 SUGGEST 换成另一条"）也是错的：
 *    它依赖"上一手改了盘面"这个前提，而**判断前提本身**用的是同一个不牢靠的时机
 *    （`waitState(…, 700)` 超时 → 认定"没改盘面"→ 直接读旧样本）。宝牌那手就是
 *    拖延超过 700ms 才让前提判断误判的。实测仍会挂。
 * ⇒ 第三版（本函数）：**不看时间、不看行号，只看内容** ——
 *   等"最新一整盘的 `seq` 真的比上次用掉的那盘大"。它慢到多晚都能等到；
 *   而那手若**真的没改盘面**（严格回弹），等不到新盘时**旧那一盘依然是对的**
 *   （盘面没变），所以超时返回当前那一盘是安全的，不是将就。
 *
 * @param seqBefore 上一轮用掉的那一盘的 seq（首轮传 -1）
 */
async function waitPassAfter(cdp, seqBefore, timeoutMs = 2500) {
    const t0 = Date.now();
    while (Date.now() - t0 < timeoutMs) {
        const p = lastDiagPass(cdp);
        if (p && p.seq > seqBefore) return p;
        if (pageOf(cdp) !== 'game') break;
        await sleep(60);
    }
    return lastDiagPass(cdp);
}

/**
 * 拖动中"牌是否始终落在格心"的硬断言（2026-10-03 加）。
 *
 * 【它测的是什么】三条都是用户真机试玩的原话：
 *   ① 「这个操作不够丝滑，拖动的时候不像原来的格子」
 *      —— 牌停在两格之间，格缝里露出棋盘底色。截图实测：「革」纸面顶边 y=565，
 *         而它所在行的正常顶边是 y=518 ⇒ 牌跨在 row1/row2 正中。
 *   ② 「拖动的时候格子会歪掉」
 *      —— 横拖时挂 ±6° 倾斜。截图实测倾角 5.45°。
 *   ③ 「而且能拉出边界之外」
 *      —— 越界橡皮筋让牌滑出棋盘。截图实测越出左边界约半张牌宽。
 * 三条都只发生在**手指还按着**的那段时间里。松手之后牌要么回弹、要么落子，
 * 一切都恢复正常 —— 所以判据必须落在**拖动过程中**，看终局永远看不出来。
 *
 * 【怎么拖】照 `[Diag] SUGGEST` 给出的轴与方向，一路拖到**贴着画布边**
 * （比棋盘边界更远），然后松手。这样"往棋盘外拖"这件事一定会被撞到。
 *
 * 【样本必须"整盘一起取"，且必须是新的一盘】
 * 每轮开跑前用 `waitPassAfter` 等一整盘**更新的**快照（BOARD/TILES/STATE/SUGGEST
 * 取自同一次 dump），不是分别 `lastDiag` 各取一条 —— 后者会拿到**两盘混起来**的
 * 数据（比如 TILES 是新的、SUGGEST 是旧的），而且这种混盘恰好能骗过所有
 * "两边对比"型的自洽检查。来龙去脉（含两个失败的修法）见 `waitPassAfter` 的注释。
 * ★ 这不是"多一层保险"，而是**必须**：实测不这么做时，6 轮里会间歇性挂 1 轮，
 *   报的还是"整段拖动一条 DRAG 行都没打"，看着像拖拽坏了。
 *
 * 【判据】逐条检查拖动途中的每一行 `[Diag] DRAG`：
 *   · 节点 === 期望（±1 取整误差）→ 破 = "不像原来的格子"
 *   · |角度| ≤ 0.01               → 破 = "格子会歪掉"
 *   · |节点| ≤ 最外一格的中心      → 破 = "拉出边界之外"
 * ⚠️ 第三条务必看**节点位置**，不是看落点格 —— 落点格是 clampSlide 的输出，
 *   天然被夹在棋盘内，"格越界"这个判据**永远不可能成立**（详见循环里的长注释，
 *   2026-10-03 的负控实验实测到过）。
 *
 * 【负控实验：证明这些判据不是摆设】（2026-10-03 实际跑过一次）
 *   把 GamePage.onMove 的显示位置临时改回旧实现（跟手自由滑 + rotate 5.45°）后
 *   重跑本动作，应当**逐条报红**：① 节点≠格心 ② 角度=5.45° ③ 节点超出棋盘范围。
 *   负控的价值在于：只跑正控时，"结构上恒真"的假判据与真判据看起来一模一样。
 *   ★ 上面第三条判据就是这么被揪出来的。
 *
 * ⚠️ 必须**逐条**查，不能只看最后一条：牌完全可以在中途跑出去再回来，
 *   末条照样合法 —— 只查末条等于把这一整轮变成摆设。
 * ⚠️ 一行 DRAG 都没有 = 牌整段没跨过一次格 → 判失败。那是事件层或吸附逻辑坏了，
 *   不能让"零覆盖"冒充绿灯（空转的一轮比红灯更坏）。
 * ⚠️ 拖动必须真的跨过若干格，否则三条判据平凡成立、这一轮等于空转。
 *
 * @param m bootAndCheck 拿到的尺寸信息（`{ canvas: { cssW, cssH, left, top } }`）。
 *          只需要 `canvas.cssH` —— 用它换算出画布在**设计单位**下的半高，
 *          好让"拖到画布边"这个终点落在画布内、指针不会中途离开 canvas。
 *          ⚠️ 执行段那个变量叫 `m`（`const m = await bootAndCheck('')`），
 *             **不叫 `mm`** —— `mm` 是 bootAndCheck 内部的局部名，外面看不见。
 */
async function chaiziDragCellTest(cdp, cx, cy, times, m) {
    let ok = 0, fail = 0, skipped = 0;
    let maxCells = 0;      // 所有轮次里单轮跨过的最多格数（覆盖度信号，见函数尾）
    // 画布边界（设计单位）。留 8 设计px 的余量，保证指针**始终不离开 canvas** ——
    // 指针一旦离开 canvas，浏览器就不再往 canvas 派 mousemove，拖动会半路断掉，
    // 那会伪装成"牌不跟手"，反而把这一轮的结论带偏。
    const halfW = UNIT_W / 2 - 8;
    const halfH = (m.canvas.cssH / PS) / 2 - 8;

    let passSeq = -1;   // 上一轮用掉的那一盘的 STATE seq（判"有没有更新的一盘"的判据）

    for (let k = 0; k < times; k++) {
        // ★ 取样本之前先等到"**比上一轮更新的一整盘**"打出来 —— 这一步不能省。
        //   判据是**内容**（同一盘的 STATE seq），不是时间、也不是行号；
        //   三版修法的来龙去脉见 waitPassAfter 的注释（前两版都是错的，别再写回去）。
        const pass = await waitPassAfter(cdp, passSeq, 2500);
        if (!pass) {
            skipped++;
            console.log(`    （第 ${k + 1} 轮拿不到完整的 diag 快照 —— 跳过）`);
            break;
        }
        passSeq = pass.seq;

        const geo = parseBoardGeo(pass.geoLine);
        const sug = parseSuggest(pass.sugLine);
        if (!geo || !sug) {
            skipped++;
            console.log(`    （第 ${k + 1} 轮：seq=${pass.seq} 这一盘没有可拖的走法 —— 跳过）`);
            break;
        }

        // ★ 自洽检查（**同一盘内**）：SUGGEST 说的起点格上必须真有那张牌。
        //   因为 TILES 与 SUGGEST 现在取自**同一盘**（见 lastDiagPass），这一条
        //   不再用来挡竞态，而是挡"游戏给出的 SUGGEST 与自己的盘面对不上"。
        //   那属于真问题，但判成**跳过**（取不到样本）而不是"手感坏了"，
        //   免得把性质完全不同的事混成同一个红。全轮都跳过时执行段会整体判失败。
        const tilesNow = parseTiles(pass.tilesLine);
        if (!tilesNow || !tileAt(tilesNow, sug.char, sug.fromR, sug.fromC)) {
            skipped++;
            console.log(`    （第 ${k + 1} 轮：seq=${pass.seq} 这一盘的 SUGGEST 起点 `
                + `(${sug.fromR},${sug.fromC}) 上没有「${sug.char}」—— 取不到样本，跳过）`);
            continue;
        }

        // 起点 = 那张牌所在格的格心；终点 = 沿同一轴贴到画布边
        const fromDX = geo.cx + cellLocalX(geo, sug.fromC);
        const fromDY = geo.cy + cellLocalY(geo, sug.fromR);
        const horiz = sug.toR === sug.fromR;
        const dir = horiz ? Math.sign(sug.toC - sug.fromC) : Math.sign(sug.toR - sug.fromR);
        // 屏幕坐标 y 轴朝下、棋盘局部坐标 y 轴朝上 ⇒ 纵向要取负号
        const toDX = horiz ? (dir > 0 ? halfW : -halfW) : fromDX;
        const toDY = horiz ? fromDY : (dir > 0 ? -halfH : halfH);

        console.log(`    [${k + 1}] 拖「${sug.char}」(${sug.fromR},${sug.fromC}) 沿`
            + `${horiz ? '横' : '竖'}轴一路拖到画布边（比棋盘边界更远），途中逐条查 DRAG 行`);

        const mark = cdp.consoleLines.length;
        await cdp.dragAt(cx + fromDX * PS, cy - fromDY * PS,
            cx + toDX * PS, cy - toDY * PS, 14);
        await sleep(700);

        const rows = cdp.consoleLines.slice(mark).map(parseDrag).filter(Boolean);
        const problems = [];
        if (rows.length === 0) {
            problems.push('整段拖动一条 DRAG 行都没打 —— 牌根本没跨过格'
                + '（事件层没接上？还是吸附逻辑把位移吞掉了？）');
        }
        // 棋盘允许的**节点位置**范围：最外一格的中心。
        // 例（L1 实测 cols=6 rows=7 pitch=112）：x ∈ [-280, 280]、y ∈ [-336, 336]。
        const maxX = (geo.cols - 1) / 2 * geo.pitch;
        const maxY = (geo.rows - 1) / 2 * geo.pitch;
        for (const d of rows) {
            if (Math.abs(d.nx - d.ex) > 1 || Math.abs(d.ny - d.ey) > 1) {
                problems.push(`跨到格(${d.r},${d.c})时节点在(${d.nx},${d.ny})，`
                    + `格心是(${d.ex},${d.ey}) —— 牌没落在格心上（"不像原来的格子"）`);
            }
            if (Math.abs(d.angle) > 0.01) {
                problems.push(`跨到格(${d.r},${d.c})时角度=${d.angle}° —— `
                    + '牌被倾斜了（"格子会歪掉"）');
            }
            // ★ ③「能拉出边界之外」—— 判据是**节点位置**，不是落点格。
            //
            // ⚠️⚠️ 这里 2026-10-03 写过一版错的，留档免得再写回去：
            //   一开始写的是"落点格 (r,c) 必须在 rows×cols 之内"，看着很对，其实
            //   **永远不可能成立**。原因：`格=` 就是 clampSlide 的输出，而 clampSlide
            //   内部已经把 r/c 夹在 range 里（`Math.max(range.up, Math.min(range.down, r))`），
            //   所以"格越界"这个判据恒真 —— 等于没测。
            //   ★ 这条是**负控实验**逼出来的：把显示改回"跟手自由滑 + 倾斜"再跑，
            //     ①（节点≠格心）和②（角度 5.45°）都乖乖报红，
            //     唯独"格在棋盘内"那一行**依然全绿**，而牌明明已经跑到画布边上了。
            //     若不做负控、只看"正控全绿"，这条空转的判据会一直冒充有效断言。
            //   ⇒ 正确的判据是"牌的**节点位置**不得超过最外一格的中心"。
            if (Math.abs(d.nx) > maxX + 1 || Math.abs(d.ny) > maxY + 1) {
                problems.push(`跨到格(${d.r},${d.c})时节点在(${d.nx},${d.ny})，`
                    + `超出棋盘范围 x∈[${-maxX},${maxX}] y∈[${-maxY},${maxY}]`
                    + '（"能拉出边界之外"）');
            }
            // 下面这条只是便宜的自检（见上：它被 clampSlide 结构性保证，
            // 正常永远不触发）。留着是为了万一将来 diag 行的口径被改，
            // 能立刻看出来，而不是让整个判据悄悄失效。
            if (d.r < 0 || d.r >= geo.rows || d.c < 0 || d.c >= geo.cols) {
                problems.push(`落点格(${d.r},${d.c})跑到 ${geo.rows}×${geo.cols} 棋盘之外`
                    + '（这条被 clampSlide 结构性保证，触发即说明诊断口径被改过）');
            }
        }
        if (problems.length === 0) {
            ok++;
            if (rows.length > maxCells) maxCells = rows.length;
            // 打出实际跨过的格子序列 —— 这是"这一轮真的动了"的凭据，
            // 不是"没报错所以大概没问题"。
            const cells = rows.map((d) => `${d.r},${d.c}`).join(' → ');
            console.log(`       ✅ 跨了 ${rows.length} 格，每格都正好落在格心、`
                + `角度恒 0、且全在棋盘内：${cells}`);
        } else {
            fail++;
            for (const p of problems) console.log(`       ❌ ${p}`);
            // 失败时把原始取样整段倒出来，便于直接对照 GamePage.onMove 的输出
            console.log('       ── 原始 DRAG 取样 ──');
            for (const d of rows) {
                console.log(`         字=${d.char} 格=${d.r},${d.c} `
                    + `节点=(${d.nx},${d.ny}) 期望=(${d.ex},${d.ey}) 角度=${d.angle}`);
            }
        }
    }
    // 覆盖度信号：如果每一轮都只跨 1 格，"三条判据全绿"的信息量其实很薄 ——
    // 那种情况下多跑几轮、或换一关再跑，比盯着这个 ✅ 更有意义。
    if (ok > 0 && maxCells <= 1) {
        console.log(`    ⚠️ 覆盖度偏薄：${times} 轮里单轮最多只跨过 ${maxCells} 格。`
            + '判据本身没错（被挡住的走法就是只能跨 1 格），但建议加轮次或换关再跑一遍。');
    }
    return { ok, fail, skipped };
}

//  gapMs：两次点击之间的间隔。默认 800（悠闲地玩），但**消除动效的验收**
//  （碰的撞击 ≈0.5s、"吃"的流水汇合 ≈0.4s）需要按动效时长对齐节奏，
//  260~450ms 比较合适。所以它必须是参数，不能写死。
//  ⚠️ 别再把它写成"连章窗口" ——「连章」= **连击**，是初版误做、**已整体删除**的
//     机制，与「吃」（顺子）毫无关系（见 CFG.MOTION §十五）。
//  另外它认识"这一步会不会触发消除"：决策规则 ① 就是"槽里已有 2 张同牌面 →
//  补第 3 张"，所以只要看**槽内该牌面的张数是不是 2**，就能在点击之前预知
//  「这里马上要消」。这让「撞击帧连拍」成为可能 —— 只在这一步前后连拍，
//  其余步照常走，既拿得到动画中间帧，又不会产出上百张无用截图。
async function autoPlay(cdp, cx, cy, steps, outDir, shotIndex, gapMs = 800, burst = []) {
    let clicked = 0;
    let clears = 0;
    console.log(`    节奏：每步间隔 ${gapMs}ms`);
    if (burst.length) console.log(`    撞击帧连拍：消除步后 +[${burst.join(', ')}]ms 各截一张`);

    for (let s = 0; s < steps; s++) {
        const line = latestPickableLine(cdp);
        const list = parsePickable(line);
        if (list.length === 0) {
            console.log('    （已无可点牌，自动试玩结束）');
            break;
        }

        // 决策顺序（越靠前越优先）：
        //   ① 槽里已有 2 张同牌面 → 补第 3 张，立刻消
        //   ② 槽里已有 1 张同牌面 → 补到 2 张
        //   ③ 可点牌里数量最多的牌面 → 有富余才敢开始凑
        //   ④ 都没有就随便点一张
        const slotKeys = parseSlotKeys(line);
        const slotCnt = new Map();
        for (const k of slotKeys) slotCnt.set(k, (slotCnt.get(k) || 0) + 1);

        let target = null;
        const bySlot = [...slotCnt.entries()].sort((a, b) => b[1] - a[1]);
        for (const [k] of bySlot) {
            const hit = list.find((t) => t.key === k);
            if (hit) { target = hit; break; }
        }

        if (!target) {
            const cnt = new Map();
            for (const t of list) cnt.set(t.key, (cnt.get(t.key) || 0) + 1);
            let bestKey = null;
            let bestN = 0;
            for (const [k, n] of cnt) if (n > bestN) { bestN = n; bestKey = k; }
            target = (bestN >= 3 ? list.find((t) => t.key === bestKey) : null) || list[0];
        }

        const sx = Math.round(cx + target.x * PS);
        const sy = Math.round(cy - target.y * PS);
        // 预知这一步会不会消：决策规则①挑的就是"槽里已有 2 张"的牌面
        const willClear = (slotCnt.get(target.key) || 0) === 2;
        const before = latestState(cdp);
        const seq0 = pickableSeq(cdp);
        console.log(`    [${s + 1}] 点 ${target.key} @设计(${target.x}, ${target.y})${willClear ? '  ← 预计触发消除' : ''}`);
        await cdp.clickAt(sx, sy);
        clicked++;

        if (willClear && burst.length) {
            // 撞击帧连拍：消除动画总长不到 1 秒，只有按偏移连拍才抓得到中间过程
            let t = 0;
            for (const off of burst) {
                await sleep(Math.max(0, off - t));
                t = off;
                const p = await cdp.shot(`${String(shotIndex).padStart(2, '0')}-clash-${s + 1}-${off}ms`);
                console.log(`       撞击 ${off}ms → ${p}`);
            }
            await sleep(Math.max(0, gapMs - t));
            await waitNewPickable(cdp, seq0, 1400);
        } else {
            // 等"这一步真的落地了"再继续（见 waitNewPickable 的注释）
            const waited = await waitNewPickable(cdp, seq0, 1400);
            if (waited < 0) console.log('       （这一步没有产生新牌局日志，按最小节奏继续）');
            await sleep(gapMs);
        }

        const after = latestState(cdp);
        if (before !== after) {
            clears++;
            console.log(`       状态：${after ?? '(无)'}`);
        }
    }

    // 通关/失败后游戏会延迟 2 秒跳回关卡页，这里等它跳完再继续
    await sleep(2200);
    const p = await cdp.shot(`${String(shotIndex).padStart(2, '0')}-auto`);
    console.log(`    已截图：${p}（点击 ${clicked} 次，状态变化 ${clears} 次）`);
}

// ------------------------------------------------------------
//  故意凑不成（dirty）：专门用来逼出「败局」的负向测试
// ------------------------------------------------------------
//  auto 是"聪明地玩"，永远在凑同牌面 → 永远通关，测不到失败分支。
//  失败分支（槽位满了 / 时间到）恰恰是最需要回归的：复活、结算、兜底文案
//  全挂在这条链路上，而它在真实游玩里很难稳定复现。
//
//  dirty 的策略与 auto **完全相反**：专挑"槽内该牌面张数最少"的牌点，
//  且跳过任何会让槽内某牌面凑到 3 张的牌（那会消掉，白费）。
//  结果就是槽里堆满单张散牌 → 槽位一满立刻判负。
//
//  ⚠️ 【顺带白捡的能力：它是唯一能造出「吃」的策略】
//  上面那条"跳过 n≥2"的规则让它永远不会触发「碰」；但"专拿互不相同的单张"
//  这件事本身，恰恰是**凑顺子（234条 / 456万）的前提** —— 而顺子不需要重复牌面，
//  所以 dirty 完全可能在无意中凑出一条来，此时 findMatch 的优先级
//  （先找碰、再找吃）会放行「吃」。
//  这让 dirty 意外成为**「吃」的动效验收工具**：auto 永远测不到「吃」。
// ------------------------------------------------------------
async function dirtyPlay(cdp, cx, cy, steps, outDir, shotIndex, gapMs = 700, burst = []) {
    let clicked = 0;
    console.log(`    节奏：每步间隔 ${gapMs}ms`);
    if (burst.length) console.log(`    消除帧连拍：若这一步会形成「吃」则 +[${burst.join(', ')}]ms 各截一张`);

    for (let s = 0; s < steps; s++) {
        const line = latestPickableLine(cdp);
        const list = parsePickable(line);
        if (list.length === 0) {
            console.log('    （已无可点牌，结束）');
            break;
        }

        const slotKeys = parseSlotKeys(line);
        const slotCnt = new Map();
        for (const k of slotKeys) slotCnt.set(k, (slotCnt.get(k) || 0) + 1);

        // 选槽内该牌面张数最少的一张；张数 ≥2 的直接跳过（点了会消）
        let best = null;
        let bestN = Number.POSITIVE_INFINITY;
        for (const t of list) {
            const n = slotCnt.get(t.key) || 0;
            if (n >= 2) continue;
            if (n < bestN) { bestN = n; best = t; }
        }
        if (!best) {
            console.log('    （剩下的牌一点就会消，无负数路径可走，结束）');
            break;
        }

        const sx = Math.round(cx + best.x * PS);
        const sy = Math.round(cy - best.y * PS);
        // 预知这一步会不会形成「吃」：把这张加进去后，槽内是否已有同花色 3 连号
        const willChi = wouldChi(slotKeys, best.key);
        console.log(`    [${s + 1}] 故意点 ${best.key}（槽内已有 ${bestN} 张）@设计(${best.x}, ${best.y})`
            + (willChi ? '  ← 预计形成「吃」' : ''));
        const seq0 = pickableSeq(cdp);
        await cdp.clickAt(sx, sy);
        clicked++;

        if (willChi && burst.length) {
            let t = 0;
            for (const off of burst) {
                await sleep(Math.max(0, off - t));
                t = off;
                const p = await cdp.shot(`${String(shotIndex).padStart(2, '0')}-chi-${s + 1}-${off}ms`);
                console.log(`       吃 ${off}ms → ${p}`);
            }
            await sleep(Math.max(0, gapMs - t));
            await waitNewPickable(cdp, seq0, 1400);
        } else {
            // 与 auto 同理：等这一步真的落地再决策，否则会对着过期列表重复点击
            await waitNewPickable(cdp, seq0, 1400);
            await sleep(gapMs);
        }
    }

    // 判负后游戏会延迟 2 秒弹面板，等它出来再截图
    await sleep(2400);
    const p = await cdp.shot(`${String(shotIndex).padStart(2, '0')}-dirty`);
    console.log(`    已截图：${p}（点击 ${clicked} 次）`);
}

/**
 * 预判"把 key 放进槽之后会不会立刻消除"。
 *
 * ⚠️ 规则必须与 `MatchRule.findMatch` **一致**：碰 = 3 张相同、
 *    杠 = 4 张相同、吃 = 同族（万/条/筒）连号 3 张。
 *    这里只判断"会不会消"，不需要知道消哪三张，所以比 MatchRule 略简单；
 *    但**族名与编号写法必须对齐**（`wan-5` 这种），否则会误判成"安全"，
 *    结果 fill 一填就消、永远填不满槽 —— 而现象只是"槽没满、面板没弹"，
 *    极难联想到判定规则写错了。
 */
function wouldMatch(slotKeys, key) {
    const cnt = new Map();
    for (const k of slotKeys) cnt.set(k, (cnt.get(k) || 0) + 1);
    cnt.set(key, (cnt.get(key) || 0) + 1);
    for (const n of cnt.values()) if (n >= 3) return true;   // 碰 / 杠
    const has = new Set(cnt.keys());
    for (const fam of ['wan', 'sou', 'ton']) {
        for (let t = 1; t <= 7; t++) {
            if (has.has(`${fam}-${t}`) && has.has(`${fam}-${t + 1}`)
                && has.has(`${fam}-${t + 2}`)) return true;   // 吃
        }
    }
    return false;
}

/**
 * fill：把槽位"安全地"塞到指定张数，用于逼出「槽满判负 → 看广告复活」。
 *
 * 策略：每一步在可点牌里挑一张**放进去不会引发任何消除**的，
 * 优先挑"槽内该牌面张数最少"的（保证分布均匀、能填得更满）。
 * 一张都挑不出时立即结束 —— 那说明这局的牌面组合已经不允许再塞了
 * （比如只剩两种牌面、各自再点一张就会凑成 3 张）。
 *
 * `burst`：只在**填满的那一下**（判负触发点）之后按偏移连拍，
 * 用来抓 S18 的「纸被揉皱 + 溅墨」（总长 1140ms）。
 */
async function fillPlay(cdp, cx, cy, steps, outDir, shotIndex, gapMs = 620, burst = []) {
    // 搅牌配额：最多主动消几组来把牌堆搅开（见循环里"兜底：搅牌"那段）
    const SAC_MAX = 4;
    let clicked = 0;
    let sacs = 0;
    console.log(`    节奏：每步间隔 ${gapMs}ms`);
    if (burst.length) console.log(`    判负帧连拍：填满那一下之后 +[${burst.join(', ')}]ms 各截一张`);
    for (let s = 0; s < steps; s++) {
        const line = latestPickableLine(cdp);
        const list = parsePickable(line);
        if (list.length === 0) {
            console.log('    （已无可点牌，结束）');
            break;
        }
        const slotKeys = parseSlotKeys(line);
        const slotCnt = new Map();
        for (const k of slotKeys) slotCnt.set(k, (slotCnt.get(k) || 0) + 1);

        // 这一下会不会把槽填满（＝判负触发点）
        const capM = line && line.match(/槽=\d+\/(\d+)/);
        const cap = capM ? Number(capM[1]) : 8;

        // 先按"槽内已有张数"升序，再取第一张安全的（点下去**不会**凑成组）
        const sorted = list.slice().sort(
            (a, b) => (slotCnt.get(a.key) || 0) - (slotCnt.get(b.key) || 0),
        );
        let pick = sorted.find((t) => !wouldMatch(slotKeys, t.key));
        let sacrifice = false;

        if (!pick) {
            // ---- 兜底：主动点一张"会凑成组"的牌，把牌堆搅开 ----
            //
            // 【为什么必须有这一步 —— L2/L3/L4 实测都卡在这里】
            // 叠塔结构会把**同一种牌面挤在一起**先露出来（实测 L4 开局
            // 可点 5 张里 4 张都是 `sou-6`），此时"凑 8 张互不成型的牌"
            // **根本无解** —— 填到 7 张就只剩会消的牌，`fill` 只能停。
            // 而游戏判定顺序是「入槽 → 先判消 → 没消成才判槽满」
            //（`GamePage.finish` 的调用点），所以"点一张会消的"**不会**判负，
            // 只会消掉 3 张、把牌堆搅开，露出新的可点牌 —— 池子才可能变多样。
            //
            // 约束：允许这一下把槽"顶到" cap（`<= cap`），因为游戏是
            // **先判消、再判槽满**，会消的牌入槽后槽立刻降回去，不会判负。
            // 万一 `wouldMatch` 预判与游戏不一致、这一下真的把槽填满了 ——
            // 那正好就是我们要的判负，同样不算亏。
            if (sacs < SAC_MAX && slotKeys.length + 1 <= cap) {
                pick = list.find((t) => wouldMatch(slotKeys, t.key));
                sacrifice = !!pick;
            }
        }

        if (!pick) {
            console.log('    （剩下的牌一点就会消，且已用完搅牌配额，结束）');
            break;
        }

        // sacrifice 时点是"会消的"，入槽后先走消除分支 → 不会判负
        const willLose = !sacrifice && slotKeys.length + 1 >= cap;

        const sx = Math.round(cx + pick.x * PS);
        const sy = Math.round(cy - pick.y * PS);
        console.log(`    [${s + 1}] ${sacrifice ? '搅牌' : '填槽'} ${pick.key}`
            + `（槽内已有 ${slotCnt.get(pick.key) || 0} 张，当前槽 ${slotKeys.length} 张）`
            + `@设计(${pick.x}, ${pick.y})`
            + (willLose ? '  ← 预计填满判负' : ''));
        if (sacrifice) sacs++;
        const seq0 = pickableSeq(cdp);
        await cdp.clickAt(sx, sy);
        clicked++;

        if (willLose && burst.length) {
            // 这一步点下去槽必满 → 游戏立即进结算，后面的 waitNewPickable / 再点
            // 都拿的是过期日志，会重复点同一张牌（还可能误触结算面板的按钮）。
            // 所以连拍完成后**直接收尾**，跳到函数末尾统一等面板。
            let t = 0;
            for (const off of burst) {
                await sleep(Math.max(0, off - t));
                t = off;
                const p = await cdp.shot(`${String(shotIndex).padStart(2, '0')}-loss-${off}ms`);
                console.log(`       判负 ${off}ms → ${p}`);
            }
            break;
        }
        await waitNewPickable(cdp, seq0, 1400);
        await sleep(gapMs);
    }

    // 判负后游戏会延迟约 2 秒弹面板，等它出来再截图
    await sleep(2400);
    const p = await cdp.shot(`${String(shotIndex).padStart(2, '0')}-fill`);
    console.log(`    已截图：${p}（点击 ${clicked} 次）`);
}

/**
 * 预测"这一张入槽之后，槽内是否会出现同花色 3 连号（=「吃」）"。
 *
 * 【为什么要预测而不是事后看日志】
 * 「吃」的流水汇合全程只有 300ms 左右，事后从日志里读到 `牌型=chi` 时，
 * 动画早就播完了，一张中间帧都抓不到。只有在点击**之前**就预知，
 * 才能像 auto 的撞击连拍那样，在正确的时刻按下快门。
 *
 * 牌面 key 形如 `wan-3` / `sou-11` / `ton-5`：前缀是花色，数字是点数。
 */
function wouldChi(slotKeys, k) {
    const bySuit = new Map();
    for (const key of slotKeys.concat([k])) {
        const m = key.match(/^([a-z]+)-(\d+)$/);
        if (!m) continue;
        if (!bySuit.has(m[1])) bySuit.set(m[1], new Set());
        bySuit.get(m[1]).add(Number(m[2]));
    }
    for (const nums of bySuit.values()) {
        for (const n of nums) if (nums.has(n + 1) && nums.has(n + 2)) return true;
    }
    return false;
}

/** 解析槽内牌面：'槽内=[wan-7,wan-7,ton-5]' → ['wan-7','wan-7','ton-5'] */
function parseSlotKeys(line) {
    if (!line) return [];
    const m = line.match(/槽内=\[([^\]]*)\]/);
    if (!m || !m[1].trim()) return [];
    return m[1].split(',').map((s) => s.trim()).filter(Boolean);
}

/** 取最近一条状态行里的「已清 / 槽」摘要（用来判断刚才那一下有没有真的消掉） */
function latestState(cdp) {
    const line = latestPickableLine(cdp);
    if (!line) return null;
    const m = line.match(/已清=(\d+) 槽=(\d+)\/(\d+)/);
    return m ? `已清${m[1]} 槽${m[2]}/${m[3]}` : null;
}

